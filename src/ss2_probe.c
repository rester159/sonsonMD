/* Profiled map collision lookup. C oracle is in ss2_logic.h (host/check).
 * m68000 ABI: two zero-extended 32-bit argument slots, u8 result in d0.
 * Scratch: d0/d1/a0/a1/CCR; d2/d3 are saved, all other registers preserved.
 * ss2_ram is explicitly word aligned. Reads bank 6/7 and the live map on
 * every call; no cached map state or changed collision/update ordering.
 */
#ifndef SS2_HOST
#ifdef SS2_PROBECHECK
volatile unsigned long ss2_probe_checks, ss2_probe_failures;
#endif
__asm__(
".text\n"
".align 2\n"
".globl ss2_probe_point_native\n"
"ss2_probe_point_native:\n"
" movem.l %d2-%d3,-(%sp)\n"
" lea ss2_ram,%a0\n"
/* wx = (sx + camera x) & 2047; wy likewise. x's high byte is odd. */
" moveq #0,%d0\n"
" move.b 0x45(%a0),%d0\n"
" lsl.w #8,%d0\n"
" move.b 0x46(%a0),%d0\n"
" add.w 14(%sp),%d0\n"
" and.w #0x7ff,%d0\n"
" move.w 0x48(%a0),%d1\n"
" add.w 18(%sp),%d1\n"
" and.w #0x7ff,%d1\n"
/* Source scratch coordinates are little endian. */
" move.w %d0,%d2\n"
" ror.w #8,%d2\n"
" move.w %d2,0x28(%a0)\n"
" move.w %d1,%d2\n"
" ror.w #8,%d2\n"
" move.w %d2,0x2a(%a0)\n"
" clr.b 0x61(%a0)\n"
" clr.w 0x62(%a0)\n"
/* Byte offsets of 16-bit table entries: (coordinate >> 5) * 2. */
" move.w %d1,%d2\n"
" lsr.w #4,%d2\n"
" and.w #0x7e,%d2\n"
" lea ss2_probe_row,%a1\n"
" move.w (%a1,%d2.w),%d2\n"
" move.w %d0,%d3\n"
" lsr.w #4,%d3\n"
" and.w #0x7e,%d3\n"
" lea ss2_probe_col,%a1\n"
" add.w (%a1,%d3.w),%d2\n"
" moveq #0,%d3\n"
" lea 0x1000(%a0),%a1\n"
" move.b (%a1,%d2.w),%d3\n"
" lsl.w #3,%d3\n"
/* Quadrant byte offset within the 32x32 metatile. */
" and.w #0x10,%d0\n"
" lsr.w #3,%d0\n"
" and.w #0x10,%d1\n"
" lsr.w #2,%d1\n"
" or.w %d1,%d0\n"
" add.w %d0,%d3\n"
" moveq #0,%d0\n"
" move.b 0x5e(%a0),%d0\n"
" lsl.w #8,%d0\n"
" move.b 0x5d(%a0),%d0\n"
" add.w %d3,%d0\n"
" addq.w #1,%d0\n"
" and.w #0x1fff,%d0\n"
/* stage bit 2 selects pointer offset 24 or 28 (bank 6 or 7). */
" moveq #0,%d1\n"
" move.b 0x69(%a0),%d1\n"
" and.w #4,%d1\n"
" lea ss2_banks,%a1\n"
" move.l 24(%a1,%d1.w),%a1\n"
" move.b (%a1,%d0.w),%d0\n"
" and.w #15,%d0\n"
" beq.s 4f\n"
" cmp.b #2,%d0\n"
" beq.s 1f\n"
" cmp.b #3,%d0\n"
" beq.s 2f\n"
" cmp.b #4,%d0\n"
" bne.s 3f\n"
" move.b #1,0x63(%a0)\n"
" bra.s 3f\n"
"1: move.b #1,0x61(%a0)\n"
" moveq #0,%d0\n"
" bra.s 4f\n"
"2: move.b #1,0x62(%a0)\n"
"3: moveq #1,%d0\n"
"4: movem.l (%sp)+,%d2-%d3\n"
" rts\n"
);
/* Strided 24-bit position += signed 16-bit velocity. MOVE preserves X,
 * allowing the original byte carries to use ADDX directly. d2 preserved. */
__asm__(
".text\n.align 2\n.globl ss2_obj_motion_native\n"
"ss2_obj_motion_native:\n"
" move.l %d2,-(%sp)\n"
" move.l 8(%sp),%a0\n"
" move.b 0x5ba(%a0),%d2\n"
" smi %d0\n"
" move.b 0x4ba(%a0),%d1\n"
" add.b 0x5da(%a0),%d1\n"
" move.b %d1,0x4ba(%a0)\n"
" move.b 0x49a(%a0),%d1\n"
" addx.b %d2,%d1\n"
" move.b %d1,0x49a(%a0)\n"
" move.b 0x47a(%a0),%d1\n"
" addx.b %d0,%d1\n"
" move.b %d1,0x47a(%a0)\n"
" move.b 0x5fa(%a0),%d2\n"
" smi %d0\n"
" move.b %d0,ss2_ram+0x30\n"
" move.b 0x51a(%a0),%d1\n"
" add.b 0x61a(%a0),%d1\n"
" move.b %d1,0x51a(%a0)\n"
" move.b 0x4fa(%a0),%d1\n"
" addx.b %d2,%d1\n"
" move.b %d1,0x4fa(%a0)\n"
" move.b 0x4da(%a0),%d1\n"
" addx.b %d0,%d1\n"
" move.b %d1,0x4da(%a0)\n"
" move.l (%sp)+,%d2\n"
" rts\n"
);

#endif
