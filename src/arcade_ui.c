void arcade_font_load(void)
{
    VDP_loadTileData(font, TILE_FONT_INDEX, 96, DMA);
}
void arcade_menu_begin(u8 logo)
{
    u16 x,y;
    VDP_setScreenWidth256();
    VDP_setPlaneSize(64,32,TRUE);
    VDP_setTextPlane(BG_A);
    VDP_setHorizontalScroll(BG_A,0); VDP_setVerticalScroll(BG_A,0);
    VDP_setHorizontalScroll(BG_B,0); VDP_setVerticalScroll(BG_B,0);
    VDP_clearPlane(BG_A,TRUE); VDP_clearPlane(BG_B,TRUE);
    VDP_setBackgroundColor(0);
    VDP_resetSprites(); VDP_setSprite(0,0,0,SPRITE_SIZE(1,1),0); VDP_updateSprites(1,DMA);
    arcade_font_load();
    if(logo)
    {
        PAL_setColors(0,ss_pal_char,16,CPU);
        VDP_loadTileData(ss_title_tiles,0,SS_TITLE_TILE_COUNT,DMA);
        for(y=0;y<11;y++) for(x=0;x<32;x++)
            VDP_setTileMapXY(BG_A,ss_title_nametable[(y+1)*32+x],x,y);
    }
}
