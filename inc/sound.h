/* sound.h -- SonSon NATIVE audio: faithful arcade music + SFX, Z80/V-Int-driven.
 *
 * ===========================================================================
 *  WHAT THIS IS
 * ===========================================================================
 *  SonSon's arcade board (Capcom 1984) has a dedicated sound MC6809 driving TWO
 *  AY-3-8910A PSGs (verified via MAME -listxml sonson). AY#2 carries the MUSIC,
 *  AY#1 the SFX (battery-dump fact, sibling-port RE). The main CPU triggers a
 *  sound by latching a 1-byte COMMAND (arcade $3010) + a FIRQ strobe ($3019);
 *  the sound 6809 sequences the AYs in response.
 *
 *  We reproduce that FAITHFULLY without running the sound 6809 (the native
 *  doctrine forbids the ~35 vl/frame transliteration). Each command's AY
 *  register-write stream was RECORDED ONCE from the sibling port's *verified*
 *  transliterated 6809 driver and is REPLAYED here at ~zero CPU cost
 *  (sound_replay_data.c, generated by tools/mame/encode_replay.py). The replayed
 *  AY register state is mapped to the Genesis hardware exactly as the verified
 *  port does it:
 *      AY#2 (music) -> PSG  (3 squares + noise -- exact AY timbre class)
 *      AY#1 (SFX)   -> YM2612 FM ch0-2 (single-operator square-ish voice)
 *
 * ===========================================================================
 *  FRAME-RATE DECOUPLING (the key lesson from the sibling port)
 * ===========================================================================
 *  The replay is advanced from the HARDWARE V-Blank interrupt (snd_vblank(),
 *  wired via SYS_setVIntCallback in snd_init), which fires at a constant ~60Hz
 *  and is NEVER dropped no matter how busy the game loop gets. Each V-Blank
 *  advances a fixed 8 replay ticks = 480Hz, the arcade sound-IRQ rate. So the
 *  music keeps tempo + the SFX stay crisp even in the heaviest scene -- the
 *  Genesis mirror of SonSon's separate sound CPU. The 68000 game loop costs
 *  nothing per frame for audio beyond the cheap V-Int tick.
 *
 * ===========================================================================
 *  COMMAND NUMBERS (verified by tapping the arcade sound-command latch in MAME)
 * ===========================================================================
 *  The maincpu latches a 1-byte command that the sound 6809 reads; in MAME's
 *  `sonson` driver the latch is the :soundlatch device (read via the lua
 *  save-item API; the RE's $3010/$A000 are the port's abstraction of it). Each
 *  number below was VERIFIED by tapping that latch live and correlating it with
 *  the on-screen event (tools/mame/ss_*.lua):
 *
 *  0x18  main in-game / level BGM      (start-of-game; held through play)
 *  0x0B  player FIRE / shot SFX         (1:1 with each fire press, isolated)
 *  0x01  coin
 *  0x16+0x10  round / "GET READY" music (plays right after 0x18 on game start)
 *
 *  0x08  ENEMY-DEFEAT SFX  -- VERIFIED 2026-06-17: across the attract demo, 0x08
 *        is latched for 201 frames WHILE an enemy death-animation (sprite codes
 *        307..310) is on screen vs only 68 frames when none is (75% co-occurrence;
 *        every other command is the opposite). Confirmed again by the latch-change
 *        ordering: 0x08 fires right at each enemy-death onset. (ss_corr08 / ss_seq)
 *  0x14  PLAYER-DEATH SFX  -- VERIFIED 2026-06-17: forcing the hero to die in the
 *        live game (walk into enemies, no fire), 0x14 is the command sustained
 *        through every player death and appears ONLY at death -- never in the
 *        combat vocabulary. (ss_pdeath2)
 *  0x02  ITEM/PICKUP SFX (low tier) -- VERIFIED 2026-06-17: correlating the latch
 *        with the live score ($006C-$006F BCD), 0x02 fires on every small +10
 *        pickup during the hero's run-and-collect locomotion (the low-value item),
 *        never on the death burst. The dedicated low-pickup sound. (ss_iso2/ss_iso3)
 *  0x0C  HIGH-VALUE PICKUP / BONUS SFX -- VERIFIED 2026-06-17: 0x0C fires EXACTLY on
 *        every +500 score event, in BOTH the attract demo (fr1949 sc->500, fr3027
 *        sc->1010) AND driven play (fr3435 sc 180->680), with a bonus-number sprite
 *        (code 50) present -- a distinct, higher-pitched pickup for the big-value
 *        fruit/bonus, separate from the +10 0x02 item. Clean SFX-slot one-shot
 *        stream (sound_replay_data.c off 0xA4B). (ss_iso2/ss_iso3/ss_deep)
 *  0x04  EXTRA-LIFE / 1-UP CUE -- VERIFIED 2026-06-17: parking the score just below a
 *        DSW2 bonus threshold (ss_extra) and letting play push it across, 0x04 fires
 *        the frame the score crosses the threshold -- proven at TWO thresholds (20K:
 *        score 19950->20100; 80K: 79950->80100) -- and is ABSENT from every normal-
 *        play / attract / death capture. Its handler (sound $EB51) is a guarded
 *        fire-and-hold jingle voice; recorded as a short music-slot flourish (495B).
 *        This is the cue check_extra_life() plays at each bonus crossing. (ss_extra)
 *
 *  UN-ISOLABLE HEADLESS (real handlers in the sound ROM dispatch $E678, non-empty
 *  SFX streams, but never triggered by any reachable attract/driven/forced-deep-wave
 *  path -- need a specific in-game event not reproducible headless; NOT wired, to
 *  avoid guessing): 0x07 ($E7D2), 0x09 ($E804), 0x0A ($E82A), 0x0E ($E880),
 *  0x0F ($E894). And 0x06/0x05 (shared handler $E7C2, a recurring combat/ambient
 *  SFX) are recorded into the MUSIC slot, so arming them would disturb the BGM --
 *  left out pending a clean SFX-slot re-record. EMPTY streams (cannot play at all):
 *  0x03, 0x0D, 0x12, 0x15.
 */
#ifndef SONSON_NATIVE_SOUND_H
#define SONSON_NATIVE_SOUND_H

#include <genesis.h>

/* EXTRA-LIFE (1-up) CUE -- ISOLATED + VERIFIED 2026-06-17 as command 0x04. Earlier
 * attempts mis-flagged 0x06 (a recurring combat SFX that recurs at non-threshold
 * scores). The clean isolation: park the score just below a DSW2 0x18 bonus threshold
 * and let play push it across (tools/mame/ss_extra.lua, reading the :soundlatch
 * save-item + the live BCD score $006C-$006F). 0x04 fires the frame the score crosses
 * the threshold, reproduced at the 20K (19950->20100) AND 80K (79950->80100) crossings,
 * and never appears in any normal-play / attract / death capture. Its handler (sound
 * $EB51) is a guarded fire-and-hold jingle. SND_CMD_1UP is now DEFINED to 0x04.
 *
 * LAYERED PLAYBACK (the clean fix, 2026-06-17): 0x04's recorded stream is a 3-voice
 * AY#2/PSG MUSIC jingle, and the index routes it to the single music slot -- arming
 * it via snd_command() REPLACES the BGM (and the generator's is_music FORCE-LOOP even
 * made the one-shot jingle loop forever). The arcade instead layered the jingle over
 * the music on a spare sound-CPU channel. We reproduce THAT: snd_play_1up() drives the
 * jingle on a DEDICATED replay channel + private AY register file rendered to the
 * YM2612's second FM bank (channels 3-5) -- the spare FM voices the SFX (ch0-2) and the
 * PSG BGM never touch. Three AY squares -> three YM squares (same timbre class as every
 * SFX here), re-encoded as a proper ONE-SHOT (plays once ~3.2 s, self-silences). So the
 * BGM + SFX are bit-for-bit unaffected and the 1-up truly LAYERS, exactly like the
 * arcade. check_extra_life() calls snd_play_1up() (gated by SND_1UP_ENABLE, now ON). */
#define SND_CMD_1UP         0x04    /* extra-life / 1-up jingle (VERIFIED; layered on YM ch3-5) */
#define SND_1UP_ENABLE      1       /* layered playback is faithful now -> auto-play it  */

/* Verified SonSon sound-command numbers (see header comment + sound.c). */
#define SND_CMD_STOP        0x00    /* halt + silence (arcade pairs 00+song)     */
#define SND_CMD_COIN        0x01    /* coin insert jingle                        */
#define SND_CMD_FIRE        0x0B    /* player shot SFX  (CONFIRMED)              */
#define SND_CMD_ENEMY       0x08    /* enemy-defeat SFX (VERIFIED 2026-06-17)    */
#define SND_CMD_ITEM        0x02    /* low-value item/pickup SFX (VERIFIED +10)  */
#define SND_CMD_BONUS       0x0C    /* high-value pickup/bonus SFX (VERIFIED +500)*/
#define SND_CMD_DEATH       0x14    /* player-death SFX (VERIFIED 2026-06-17)    */
#define SND_CMD_BGM_GAME    0x18    /* main in-game level BGM (CONFIRMED)       */
#define SND_CMD_ROUND_A     0x16    /* round-intro music part A                  */
#define SND_CMD_ROUND_B     0x10    /* round-intro music part B (round selector) */

/* Initialise the audio subsystem: park the Z80 (NULL driver, bus held so the
 * 68k YM writes land), set up the YM SFX voice, clear the replay slots, and
 * install the V-Blank callback that advances the replay. Call ONCE when entering
 * the game -- AFTER the CAPCOM splash (which uses + resets the YM directly and
 * returns the Z80 to SGDK's clean halt). Safe to call again on re-entry. */
void snd_init(void);

/* Stop all audio + silence the chips, and (optionally) detach the V-Blank
 * callback. Call when leaving the game back to the front-end so the splashes own
 * the sound hardware again. */
void snd_shutdown(void);

/* Fire a raw sound command (the arcade $3010 latch value). Routes music commands
 * to the music slot + SFX to the SFX slot, exactly like the arcade driver; an
 * SFX never disturbs the running music (separate chips / masked mixer). Cheap:
 * just arms the replay stream pointer(s); the V-Blank tick does the work. */
void snd_command(u8 cmd);

/* Play the extra-life / 1-up jingle (cmd 0x04) LAYERED over the BGM, on the
 * YM2612's second FM bank -- the music + SFX are untouched. One-shot (~3.2 s).
 * Use this (not snd_command(SND_CMD_1UP), which would replace the BGM). */
void snd_play_1up(void);

/* Convenience wrappers for the wired game events (clearer call sites). */
static inline void snd_play_bgm(void)  { snd_command(SND_CMD_BGM_GAME); }
static inline void snd_sfx_fire(void)  { snd_command(SND_CMD_FIRE); }
static inline void snd_sfx_enemy(void) { snd_command(SND_CMD_ENEMY); }  /* enemy defeat   */
static inline void snd_sfx_item(void)  { snd_command(SND_CMD_ITEM); }   /* low-value pickup  */
static inline void snd_sfx_bonus(void) { snd_command(SND_CMD_BONUS); }  /* high-value pickup */
static inline void snd_sfx_death(void) { snd_command(SND_CMD_DEATH); }  /* player death   */
static inline void snd_stop(void)      { snd_command(SND_CMD_STOP); }

/* Round-intro music (arcade plays 0x16 then 0x10 at a round/level start). */
static inline void snd_play_round(void) { snd_command(SND_CMD_ROUND_A); snd_command(SND_CMD_ROUND_B); }

#endif /* SONSON_NATIVE_SOUND_H */
