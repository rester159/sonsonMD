#!/usr/bin/env python3
"""Emit typed source animation graphs and motion vectors, with native tile IDs."""
from pathlib import Path
import json
from arcade_foe_data import extract
import gen_anim,gen_assets
r=Path(__file__).resolve().parents[1];d=extract(r/'arcade')
# Native move uses a signed16-bit sum with the fractional byte.
assert all(-384<=dx<=384 for row in d['vectors'] for dx,dy in row)
_,table,_,_=gen_anim.bake(gen_assets.Roms(str(r/'arcade')),290)
assert table[-1][0]=='ARCADE_FOE_POSES'
tiles={tuple(key):value[0]for key,value in zip(d['poses'],table[-1][2])}
s='/* Generated by tools/gen_arcade_foes.py; verified main MC6809 revision. */\n#include "arcade_foes.h"\n'
s+='const ArcadeFoeFrame arcade_foe_frames[]={\n'
for f in d['frames']:
 key=(f['code']+((f['attr']&32)<<3),f['attr']&31)
 s+='    {%d,%d,%d,%d,%d}, /* source %04X */\n'%(f['next'],tiles[key],f['code'],f['attr'],f['duration'],f['address'])
s+='};\n'
for name,values in d['roots'].items():s+='const u16 arcade_foe_%s[%d]={%s};\n'%(name,len(values),','.join(map(str,values)))
s+='const ArcadeFoeVector arcade_foe_vectors[3][5]={\n'
for row in d['vectors']:s+='    {'+','.join('{%d,%d}'%v for v in row)+'},\n'
s+='};\nconst ArcadeFoePlayer arcade_foe_empty_target={%d,%d,0,0};\n'%(d['empty_target']['x'],d['empty_target']['y'])
(r/'src/arcade_foe_data.c').write_text(s);(r/'out/parity-audit/foe-extraction.json').write_text(json.dumps(d,indent=2)+'\n');print('Extracted',len(d['frames']),'animation frames;',len(d['poses']),'poses')

i_keys=[(code,9)for code in range(0x60,0x6e)]+[(0x1a,7),(0x1b,7),(0x1c,7),(0,7),(3,7),(0x31,4),(0x31,3)]
i_source='/* Generated by tools/gen_arcade_foes.py. */\n#include "arcade_i.h"\n'
i_source+='static const u16 tiles[21]={'+','.join(str(tiles[k])for k in i_keys)+'};\n'
i_source+='u16 arcade_i_tile(u8 code,u8 attr)\n{\n    if(code>=0x60 && code<=0x6d)return tiles[code-0x60];\n    if(code>=0x1a && code<=0x1c)return tiles[14+code-0x1a];\n    if(code==0)return tiles[17];\n    if(code==3)return tiles[18];\n    return tiles[(attr&31)==4?19:20];\n}\n'
(r/'src/arcade_i_art.c').write_text(i_source)

life_source='/* Generated by tools/gen_arcade_foes.py; AD9B/AE99 poses. */\n#include "arcade_life.h"\n'
life_source+='u16 arcade_life_tile(u8 code,u8 attr)\n{\n'
for bank in (0,1):
 life_source+=('    if' if bank==0 else '    else if')+'((attr&31)==%d)\n    {\n        switch(code)\n        {\n'%bank
 for code,b in d['life_poses']:
  if b==bank:life_source+='            case 0x%02x:return %d;\n'%(code,tiles[(code,b)])
 life_source+='        }\n    }\n'
life_source+='    return 0; /* Invalid source pose: no tile. */\n}\n'
(r/'src/arcade_life_art.c').write_text(life_source)
