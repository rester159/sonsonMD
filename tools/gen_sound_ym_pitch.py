#!/usr/bin/env python3
"""Exact 12-bit AY period -> existing YM block/F-number bytes, moved offline."""
from pathlib import Path
import argparse
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
root=Path(__file__).resolve().parents[1]
values=[0]  # Period zero is silent; no pitch write uses this entry.
for period in range(1,4096):
    total=1845281//period
    block=0
    while total>=2048 and block<7:
        total>>=1
        block+=1
    total=min(total,2047)
    values.append((block<<11)|total)
source='/* Generated by tools/gen_sound_ym_pitch.py; exact existing mapping. */\n#include "sound_ym_pitch.h"\nconst u16 sound_ym_pitch[4096]={\n'
source+=''.join('    '+','.join(f'0x{v:04x}' for v in values[i:i+16])+',\n' for i in range(0,4096,16))+'};\n'
path=root/'src/sound_ym_pitch.c'
if args.check:
    assert path.read_text()==source, 'Regenerate sound_ym_pitch.c'
else:
    path.write_text(source)
print('Verified' if args.check else 'Generated',4096,'pitch entries')
