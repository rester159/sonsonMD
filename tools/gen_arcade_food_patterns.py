#!/usr/bin/env python3
"""Canonical 2x2 food and eaten-food character/palette descriptors."""
from pathlib import Path
import hashlib
r=Path(__file__).resolve().parents[1]
b=b''.join((r/'arcade'/n).read_bytes()for n in ['ss.01e','ss.02e','ss.03e'])
assert hashlib.sha256(b).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
s='/* Generated by tools/gen_arcade_food_patterns.py. */\n#include "arcade_food_patterns.h"\n'
for name,base in [('arcade_food_patterns',0xb403),('arcade_food_eaten_patterns',0xb5c3)]:
    s+='const u8 '+name+'[20][8]={\n'
    for kind in range(-12,8):
        data=b[base+kind*8-0x4000:base+kind*8-0x4000+8]
        s+='    {'+','.join(str(v)for v in data)+'},\n'
    s+='};\n'
(r/'src/arcade_food_patterns.c').write_text(s)
(r/'inc/arcade_food_patterns.h').write_text('''/* Generated by tools/gen_arcade_food_patterns.py. */
#ifndef ARCADE_FOOD_PATTERNS_H
#define ARCADE_FOOD_PATTERNS_H
#include "arcade_types.h"
/* Indexed by (u8)(source food code+12). Each entry has four characters then
 * four source attributes, in the original two-column order. */
extern const u8 arcade_food_patterns[20][8];
extern const u8 arcade_food_eaten_patterns[20][8];
#endif
''')
