#!/usr/bin/env python3
"""Recover source 47DA front-end labels; no capture or emulator required."""
from pathlib import Path
import hashlib
import json
import gen_assets as G

ROOT = Path(__file__).resolve().parents[1]
COMMANDS = (6, 7, 8, 10, 11, 12, 13)


def generate():
    rom = b''.join((ROOT/'arcade'/n).read_bytes()
                   for n in ('ss.01e', 'ss.02e', 'ss.03e'))
    digest = hashlib.sha256(rom).hexdigest()
    assert digest == '09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
    # The original consumes address/attribute records, skips 00, handles 2F as
    # the next record and 3F as end, then subtracts 30 from each character.
    assert rom[0x7e6:0x7fe].hex() == 'aec1a6c0e6c027fcc13f272dc12f27f0c030a7890400e780'
    def byte(a):
        assert 0x4000 <= a < 0x10000
        return rom[a-0x4000]
    def word(a):
        return byte(a)*256+byte(a+1)
    gfx = G.Roms(str(ROOT/'arcade'))
    tiles, cells, groups, sources = [], [], [], []
    for command in COMMANDS:
        cursor = word(0x4821+command*2)
        start = cursor
        first = len(cells)
        while True:
            address, attr = word(cursor), byte(cursor+2)
            cursor += 3
            while True:
                assert cursor-start < 512, 'Unterminated label'
                code = byte(cursor)
                cursor += 1
                if not code:
                    continue
                if code in (0x2f, 0x3f):
                    break
                assert 0x1000 <= address < 0x1400
                code = (code-0x30) & 255
                pixels = tuple(G.bake_char_tile(gfx, code+((attr&3)<<8), attr>>2))
                if pixels not in tiles:
                    tiles.append(pixels)
                cells.append((address-0x1000, tiles.index(pixels)))
                sources.append((command, address, code, attr))
                address += 1
            if code == 0x3f:
                break
        groups.append((command, first, len(cells)-first))
    # 50E1/514F consume five seven-byte descriptors: RAM entry, attribute,
    # score cell, name cell. Preserve all byte-valued name glyphs, rather than
    # silently restricting original character data to ASCII letters.
    ranking_rows = []
    attributes = []
    for table in (0x512c, 0x51b5):
        rows = []
        for row in range(5):
            p = table+row*7
            attr = byte(p+2)
            assert attr & 3 == 0
            rows.append((word(p+3)-0x1000, word(p+5)-0x1000))
            if table == 0x512c:
                attributes.append(attr)
            else:
                assert attr == attributes[row]
        ranking_rows.append(rows)
    glyphs = []
    for attr in attributes:
        row = []
        for code in range(256):
            pixels = tuple(G.bake_char_tile(gfx, code, attr>>2))
            if pixels not in tiles:
                tiles.append(pixels)
            row.append(tiles.index(pixels))
        glyphs.append(row)
    blank_pixels = tuple(G.bake_char_tile(gfx,16,0))
    if blank_pixels not in tiles:
        tiles.append(blank_pixels)
    blank = tiles.index(blank_pixels)
    header = '''/* Generated by tools/gen_arcade_title_art.py. */
#ifndef ARCADE_TITLE_ART_H
#define ARCADE_TITLE_ART_H
#include "arcade_types.h"
/* Original 32x32 cells; caller owns viewport mapping, tile base and PAL0.
 * Logo, sprites and transitions are separate. */
typedef struct { u16 cell, tile; } ArcadeTitleCell;
typedef struct { u16 command, first, count; } ArcadeTitleGroup;
typedef struct { u16 score, name; } ArcadeTitleRankRow;
'''
    header += f'#define ARCADE_TITLE_ART_TILES {len(tiles)}\n#define ARCADE_TITLE_ART_CELLS {len(cells)}\n'
    header += f'#define ARCADE_TITLE_ART_GROUPS {len(groups)}\n'
    header += f'#define ARCADE_TITLE_BLANK {blank}\n'
    header += '''extern const u32 arcade_title_pixels[ARCADE_TITLE_ART_TILES*8];
extern const ArcadeTitleCell arcade_title_cells[ARCADE_TITLE_ART_CELLS];
extern const ArcadeTitleGroup arcade_title_groups[ARCADE_TITLE_ART_GROUPS];
extern const ArcadeTitleRankRow arcade_title_rank_rows[2][5];
extern const u16 arcade_title_rank_glyphs[5][256];
#endif
'''
    source = '/* Generated by tools/gen_arcade_title_art.py. */\n#include "arcade_title_art.h"\n'
    source += 'const u32 arcade_title_pixels[ARCADE_TITLE_ART_TILES*8]={\n'
    source += ''.join(','.join(f'0x{v:08x}' for v in tile)+',\n' for tile in tiles)+'};\n'
    source += 'const ArcadeTitleCell arcade_title_cells[ARCADE_TITLE_ART_CELLS]={\n'
    source += ''.join('{%d,%d},\n'%cell for cell in cells)+'};\n'
    source += 'const ArcadeTitleGroup arcade_title_groups[ARCADE_TITLE_ART_GROUPS]={\n'
    source += ''.join('{%d,%d,%d},\n'%group for group in groups)+'};\n'
    source += 'const ArcadeTitleRankRow arcade_title_rank_rows[2][5]={\n'
    source += ''.join('{'+','.join('{%d,%d}'%r for r in rows)+'},\n' for rows in ranking_rows)+'};\n'
    source += 'const u16 arcade_title_rank_glyphs[5][256]={\n'
    source += ''.join('{'+','.join(map(str,row))+'},\n' for row in glyphs)+'};\n'
    (ROOT/'inc/arcade_title_art.h').write_text(header)
    (ROOT/'src/arcade_title_art.c').write_text(source)
    out = ROOT/'out/parity-audit/title-art'
    out.mkdir(parents=True, exist_ok=True)
    report = {'source_sha256': digest, 'tiles': len(tiles), 'cells': len(cells),
              'groups': groups, 'source_cells': sources,
              'raw_data_bytes': len(tiles)*32+len(cells)*4+len(groups)*6+40+2560,
              'ranking_rows': ranking_rows,
              'scope': 'Front-end labels and ranking glyphs/descriptors. Not connected to title.c yet; no runtime or whole-screen parity claim.'}
    (out/'manifest.json').write_text(json.dumps(report, indent=2)+'\n')
    print({k: v for k, v in report.items() if k != 'source_cells'})


if __name__ == '__main__':
    generate()
