#!/usr/bin/env python3
"""Decode47DA result labels into exact native tiles and sparse map writes."""
from pathlib import Path
import hashlib,json
import gen_assets as G
r=Path(__file__).resolve().parents[1];g=G.Roms(str(r/'arcade'))
rom=b''.join((r/'arcade'/n).read_bytes()for n in ('ss.01e','ss.02e','ss.03e'))
sha=hashlib.sha256(rom).hexdigest()
assert sha=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
def word(a):return int.from_bytes(rom[a-0x4000:a-0x4000+2],'big')
def byte(a):assert 0x4000<=a<0x10000;return rom[a-0x4000]
tiles=[];writes=[];groups=[];sources=[]
for command in (26,32,33,34,35):
 cursor=word(0x4821+command*2);root=cursor;begin=len(writes)
 while True:
  destination=word(cursor);attr=byte(cursor+2);cursor+=3
  while True:
   code=byte(cursor);cursor+=1
   if code==0:continue
   if code in (0x2f,0x3f):break
   tilecode=(code-0x30)&255
   assert 0x1000<=destination<0x1400
   pixels=tuple(G.bake_char_tile(g,tilecode+((attr&3)<<8),attr>>2))
   if pixels not in tiles:tiles.append(pixels)
   writes.append((destination-0x1000,tiles.index(pixels)))
   sources.append((destination,tilecode,attr));destination+=1
  if code==0x3f:break
 groups.append((begin,len(writes)-begin))
 assert cursor-root<256
expected=[]
for destination,label in ((0x10e9,'CONGRATULATION'),(0x1168,'BONUS'),
 (0x1176,'PTS'),(0x11ae,'AND'),(0x11f0,'30000@PTS'),
 (0x1268,'BONUS'),(0x1276,'PTS'),(0x12ae,'AND'),(0x12f0,'30000@PTS')):
 expected.extend((destination+i,ord(c)-0x30,0x2c)for i,c in enumerate(label))
assert sources==expected
assert len(writes)==54
digits=[]
for code,attr in [(i,0x2c)for i in range(10)]+[(16,0x2c),(16,0)]:
 pixels=tuple(G.bake_char_tile(g,code+((attr&3)<<8),attr>>2))
 if pixels not in tiles:tiles.append(pixels)
 digits.append(tiles.index(pixels))
h='''#ifndef ARCADE_RESULTS_ART_H
#define ARCADE_RESULTS_ART_H
#include "arcade_types.h"
/* Own scene: tile indices are relative to the caller-selected load base.
 * Group0 title,1 P1 bonus,2 P1 marker,3 P2 bonus,4 P2 marker. */
typedef struct {u16 cell,tile;} ArcadeResultsCell;
typedef struct {u16 first,count;} ArcadeResultsGroup;
#define ARCADE_RESULTS_ART_TILES %d
#define ARCADE_RESULTS_ART_CELLS %d
extern const u32 arcade_results_pixels[ARCADE_RESULTS_ART_TILES*8];
extern const ArcadeResultsCell arcade_results_cells[ARCADE_RESULTS_ART_CELLS];
extern const ArcadeResultsGroup arcade_results_groups[5];
/* Digits0..9, leading blank10, scene-clear blank11. */
extern const u16 arcade_results_digits[12];
#endif
'''%(len(tiles),len(writes))
(r/'inc/arcade_results_art.h').write_text(h)
(r/'src/arcade_results_art.c').write_text('/* Generated by tools/gen_arcade_results_art.py. */\n#include "arcade_results_art.h"\nconst u32 arcade_results_pixels[ARCADE_RESULTS_ART_TILES*8]={\n'+''.join(','.join('0x%08x'%v for v in t)+',\n'for t in tiles)+'};\nconst ArcadeResultsCell arcade_results_cells[ARCADE_RESULTS_ART_CELLS]={\n'+''.join('{%d,%d},\n'%v for v in writes)+'};\nconst ArcadeResultsGroup arcade_results_groups[5]={'+','.join('{%d,%d}'%v for v in groups)+'};\n')
with (r/'src/arcade_results_art.c').open('a')as f:
 f.write('const u16 arcade_results_digits[12]={'+','.join(map(str,digits))+'};\n')
o=r/'out/parity-audit/results-art';o.mkdir(parents=True,exist_ok=True)
report={'source_sha256':sha,'tiles':len(tiles),'cells':len(writes),'groups':groups,'source_cells':sources,
 'scope':'Exact47DA labels only. Player/decor sprites, dynamic number tiles, scene clear, load/restore owner and runtime presentation pending.'}
(o/'manifest.json').write_text(json.dumps(report,indent=2)+'\n');print({k:v for k,v in report.items()if k!='source_cells'})
