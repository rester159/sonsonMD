#!/usr/bin/env python3
"""gen_title.py -- bake the arcade SonSon TITLE screen (tools/title_capture.json)
into native Genesis tiles + nametable + sprites, reusing gen_assets.assemble().
Emits src/ss_title.c + inc/ss_title.h with ss_title_* symbols; reuses the arcade
palettes (ss_pal_char/ss_pal_sprite, extern from ss_gfx.h). Title loads at VRAM
tile base 0 (front-end only; overwritten when the game loads its scene tiles)."""
import os, sys, json
HERE=os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0,HERE)
import gen_assets as G

BASE=0
scene=json.load(open(os.path.join(HERE,"title_capture.json")))
roms=G.Roms(os.path.join(G.REPO,"arcade"))
pack,nametable,sprites,n_char=G.assemble(roms,scene,BASE)
n=pack.total_tiles

h=open(os.path.join(G.REPO,"inc","ss_title.h"),"w",newline="\n")
h.write("/* ss_title.h -- GENERATED by tools/gen_title.py. DO NOT EDIT.\n")
h.write(" * Arcade SonSon TITLE screen baked from tools/title_capture.json. */\n")
h.write("#ifndef SS_TITLE_H\n#define SS_TITLE_H\n#include <genesis.h>\n#include \"ss_gfx.h\" /* SSSprite + ss_pal_char/sprite */\n\n")
h.write("#define SS_TITLE_TILE_BASE   %d\n"%BASE)
h.write("#define SS_TITLE_TILE_COUNT  %d\n"%n)
h.write("#define SS_TITLE_CHAR_TILE_COUNT %d\n"%n_char)
h.write("#define SS_TITLE_SPRITE_COUNT %d\n\n"%len(sprites))
h.write("extern const u32 ss_title_tiles[SS_TITLE_TILE_COUNT*8];\n")
h.write("extern const u16 ss_title_nametable[32*32];\n")
h.write("extern const SSSprite ss_title_sprites[SS_TITLE_SPRITE_COUNT];\n")
h.write("\n#endif\n"); h.close()

c=open(os.path.join(G.REPO,"src","ss_title.c"),"w",newline="\n")
c.write('/* ss_title.c -- GENERATED by tools/gen_title.py. DO NOT EDIT.\n')
c.write(' * Arcade title screen (frame %d). Tiles reuse ss_pal_char/sprite. */\n'%scene["frame"])
c.write('#include "ss_title.h"\n\n')
c.write("const u32 ss_title_tiles[SS_TITLE_TILE_COUNT*8] = {\n")
for ti in range(n):
    longs=pack.tiles[ti*8:ti*8+8]
    c.write("    "+",".join("0x%08X"%w for w in longs)+",\n")
c.write("};\n\n")
c.write("const u16 ss_title_nametable[32*32] = {\n")
for row in range(32):
    c.write("    "+",".join("0x%04X"%w for w in nametable[row*32:row*32+32])+",\n")
c.write("};\n\n")
c.write("const SSSprite ss_title_sprites[SS_TITLE_SPRITE_COUNT] = {\n")
for s in sprites:
    sx=s["x"] if s["x"]<32768 else s["x"]-65536
    sy=s["y"] if s["y"]<32768 else s["y"]-65536
    c.write("    { %d, %d, %d, %d, %d },\n"%(sx,sy,s["tile"],s["flipH"],s["flipV"]))
c.write("};\n"); c.close()
print("gen_title: %d tiles (%d char), %d sprites, base %d"%(n,n_char,len(sprites),BASE))
