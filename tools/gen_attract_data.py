#!/usr/bin/env python3
"""Recover the contiguous attract/prelude input data; no inferred terminators."""
from pathlib import Path
import hashlib
import sys

root = Path(__file__).resolve().parents[1]
rom = b''.join((root/'arcade'/n).read_bytes() for n in ('ss.01e', 'ss.02e', 'ss.03e'))
assert hashlib.sha256(rom).hexdigest() == '09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
# 9BD2 begins the next dispatch routine, not another input pair.
assert rom[0x9bd2-0x4000:0x9bda-0x4000] == bytes.fromhex('d608588e9bda6e95')
data = rom[0x9a6e-0x4000:0x9bd2-0x4000]
assert len(data) == 356
source = '/* Generated by tools/gen_attract_data.py: source 9A6E..9BD1. */\n#include "arcade_types.h"\nconst u8 arcade_attract_data[356] = {\n'
source += ''.join('    '+', '.join(f'0x{x:02x}' for x in data[i:i+16])+',\n' for i in range(0, len(data), 16))
source += '};\n'
target = root/'src/arcade_attract_data.c'
if '--check' in sys.argv:
    assert target.read_text() == source, 'Attract data needs regeneration'
else:
    target.write_text(source)
print('Verified 356 attract/prelude bytes' if '--check' in sys.argv else 'Generated 356 attract/prelude bytes')
