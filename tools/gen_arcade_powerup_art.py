#!/usr/bin/env python3
"""Decode B2A7/B2C1 special-pickup cycles; frame IDs are not VRAM addresses."""
from pathlib import Path
import hashlib
import json
import gen_assets as G

r = Path(__file__).resolve().parents[1]
rom = b''.join((r/'arcade'/n).read_bytes() for n in ['ss.01e', 'ss.02e', 'ss.03e'])
assert hashlib.sha256(rom).hexdigest() == '09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
roms = G.Roms(str(r/'arcade'))
cells, frames = [], []
for kind, root, count in [(254, 0xb2a7, 8), (255, 0xb2c1, 4), (0, 0xe26f, 4), (1, 0xe24d, 6)]:
    for i in range(count):
        address = root + i*3
        code, attr, control = rom[address-0x4000:address-0x4000+3]
        timer = 3 if kind < 2 else 5
        assert control == ((128 | timer) if i == count-1 else timer)
        if control & 128:
            assert int.from_bytes(rom[address-0x4000+3:address-0x4000+5], 'big') == root
        pixels = G.bake_sprite_tiles(roms, code+((attr & 32)<<3), attr & 31)
        if pixels not in cells:
            cells.append(pixels)
        frames.append(dict(kind=kind, cursor=i, address=address, code=code,
                           attr=attr, timer=control & 127, cell=cells.index(pixels)))
assert len(cells) == 19
(r/'inc/arcade_powerup_art.h').write_text('''/* Generated by tools/gen_arcade_powerup_art.py. ROM cells, not VRAM. */
#ifndef ARCADE_POWERUP_ART_H
#define ARCADE_POWERUP_ART_H
#include "arcade_types.h"
#define ARCADE_POWERUP_ART_CELLS 19
extern const u32 arcade_powerup_pixels[ARCADE_POWERUP_ART_CELLS*32];
/* Attribute flip bits do not alter the stored pixels. Unsupported: 65535. */
u16 arcade_powerup_art_cell(u8 code, u8 attr);
#endif
''')
s = '/* Generated by tools/gen_arcade_powerup_art.py. */\n#include "arcade_powerup_art.h"\n'
s += 'const u32 arcade_powerup_pixels[ARCADE_POWERUP_ART_CELLS*32]={\n'
for cell in cells:
    s += '    '+','.join('0x%08x' % word for word in cell)+',\n'
s += '};\nu16 arcade_powerup_art_cell(u8 code,u8 attr)\n{\n    switch(attr & 63)\n    {\n'
for attr in sorted(set(f['attr'] & 63 for f in frames)):
    s += '        case %d: switch(code)\n        {\n' % attr
    for code, cell in sorted(set((f['code'], f['cell']) for f in frames if f['attr'] & 63 == attr)):
        s += '            case %d: return %d;\n' % (code, cell)
    s += '            default: return 65535;\n        }\n'
s += '        default: return 65535;\n    }\n}\n'
(r/'src/arcade_powerup_art.c').write_text(s)
out = r/'out/parity-audit/powerup-art'
out.mkdir(parents=True, exist_ok=True)
inputs = ['ss.01e','ss.02e','ss.03e','ss_9.m5','ss_10.m6','ss_11.m3','ss_12.m4','ss_13.m1','ss_14.m2','ssb3.h7']
manifest = dict(frames=frames, cells=len(cells), bytes=len(cells)*128,
                inputs={n:hashlib.sha256((r/'arcade'/n).read_bytes()).hexdigest() for n in inputs},
                scope='Canonical sprite pixels and lookup only; live VRAM allocation/rendering pending.')
(out/'manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
print(json.dumps(dict(cells=len(cells), bytes=len(cells)*128)))
