#!/usr/bin/env python3
"""gen_level.py -- bake a WIDE SonSon level-1 background into native Genesis 4bpp
tiles + a wide nametable, for the Phase-4 scrolling engine.

REUSES gen_assets.py's verified, byte-faithful bake (build_char path) and the
verbatim arcade palettes. Input is tools/level1_capture.json (a wide
LEVEL_COLS x 32 (code,attr) BG map stitched from the arcade attract demo's
scrolling gameplay -- see tools/ss_level_cap.lua).

Emits:
  src/ss_level.c / inc/ss_level.h
    - ss_level_tiles[SS_LEVEL_TILE_COUNT*8]  : deduped baked 4bpp char tiles
    - ss_level_map[SS_LEVEL_COLS*32]         : VDP nametable words, ROW-MAJOR
        (one word per cell), PAL0, absolute tile indices (base + local).
        Indexed map[row*SS_LEVEL_COLS + col].
    - #define SS_LEVEL_COLS, SS_LEVEL_ROWS, SS_LEVEL_TILE_BASE, SS_LEVEL_TILE_COUNT

The map is CHAR-only (the BG playfield). Sprites/enemies are not part of the
level art (the engine keeps the ss_gfx sprite tiles for the player). Char tiles
are baked exactly as gen_assets.bake_char_tile (verified byte-identical to the
port's build_char by verify_bake.py), deduped by baked-byte equality.

USAGE:
    python gen_level.py [level1_capture.json] [--arcade DIR] [--base N]
                        [--out-c PATH] [--out-h PATH]
  Defaults: level1_capture.json next to this script; arcade/ in repo; base 0
  (the engine loads ss_level_tiles at this VRAM tile index and the map words
  are absolute). Choose --base to sit AFTER the resident sprite tiles.
"""

import os
import sys
import json

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_assets as G                       # reuse Roms, bake_char_tile, tile_attr_full


def assemble_level(roms, cap, base, blank_top=0):
    """Bake the wide level. Returns (tiles[list u32], nametable[list u16],
    cols, rows, n_tiles, n_combos). Dedupes identical baked 8x8 tiles.

    blank_top: number of TOP BG rows to emit as blank (tile 0 / transparent).
    The arcade keeps rows 0-4 as a FIXED HUD overlay (score / HIGH / SONSON) that
    is NOT part of the scrolling playfield -- those cells were merely resident in
    videoram at capture time. Blanking them yields a clean scrolling playfield
    (rows 5-31, exactly the arcade's scroll region) and leaves the top of the
    screen free for the native HUD / FPS readout (drawn on the WINDOW plane).
    The black backdrop (PAL0 index 0) shows through the blanked band."""
    cols = cap["level_cols"]
    rows = cap["rows"]
    vram = cap["videoram"]
    cram = cap["colorram"]
    assert len(vram) == cols * rows, "videoram size mismatch"
    assert len(cram) == cols * rows, "colorram size mismatch"

    tiles = []                  # flat u32 (8 per 8x8 tile)
    dedup = {}                  # baked-bytes -> local tile index
    combo = {}                  # (code,bank) -> local tile index (cache)
    nametable = [0] * (cols * rows)

    for row in range(rows):
        for col in range(cols):
            i = row * cols + col
            if row < blank_top:
                nametable[i] = 0                      # blank HUD band (transparent)
                continue
            v = vram[i]
            a = cram[i]
            code = v + 256 * (a & 0x03)               # 0..1023
            bank = a >> 2                             # 0..63
            key = (code, bank)
            local = combo.get(key)
            if local is None:
                baked = G.bake_char_tile(roms, code, bank)
                local = dedup.get(baked)
                if local is None:
                    local = len(tiles) // 8
                    tiles.extend(baked)
                    dedup[baked] = local
                combo[key] = local
            nametable[i] = G.tile_attr_full(0, 0, 0, 0, base + local)

    n_tiles = len(tiles) // 8
    return tiles, nametable, cols, rows, n_tiles, len(combo)


def emit(cap, tiles, nametable, cols, rows, n_tiles, base, out_c, out_h):
    with open(out_h, "w", newline="\n") as f:
        f.write("""/* ss_level.h -- GENERATED by tools/gen_level.py.  DO NOT EDIT.
 *
 * SonSon (Capcom, 1984) WIDE level-1 background, baked to native Genesis 4bpp
 * tiles + a wide nametable, for the Phase-4 column-streaming scroll engine.
 * Reconstructed from the arcade attract demo's scrolling gameplay (md=01) by
 * stitching the 32-col videoram window across the full scroll sweep
 * (tools/ss_level_cap.lua -> tools/level1_capture.json). Palettes are the same
 * verbatim arcade PAL0 (chars) used by ss_gfx; tiles bake byte-identically via
 * the verified gen_assets.bake_char_tile (see tools/verify_bake.py).
 */
#ifndef SS_LEVEL_H
#define SS_LEVEL_H

#include <genesis.h>

""")
        f.write("/* Wide level geometry (BG cells). The map is ROW-MAJOR:\n"
                " * ss_level_map[row*SS_LEVEL_COLS + col]. */\n")
        f.write("#define SS_LEVEL_COLS %d\n" % cols)
        f.write("#define SS_LEVEL_ROWS %d\n" % rows)
        f.write("\n")
        f.write("/* VRAM tile index the engine loads ss_level_tiles[] at. The map\n"
                " * words are ABSOLUTE (already include this base). */\n")
        f.write("#define SS_LEVEL_TILE_BASE %d\n" % base)
        f.write("/* Distinct deduped 4bpp 8x8 tiles in the level's working set. */\n")
        f.write("#define SS_LEVEL_TILE_COUNT %d\n" % n_tiles)
        f.write("\n")
        f.write("extern const u32 ss_level_tiles[SS_LEVEL_TILE_COUNT * 8];\n")
        f.write("/* One VDP nametable word per cell (PAL0, no flip, low prio,\n"
                " * absolute tile index). Row-major, SS_LEVEL_COLS wide. */\n")
        f.write("extern const u16 ss_level_map[SS_LEVEL_COLS * SS_LEVEL_ROWS];\n")
        f.write("\n#endif /* SS_LEVEL_H */\n")

    with open(out_c, "w", newline="\n") as f:
        f.write("/* ss_level.c -- GENERATED by tools/gen_level.py.  DO NOT EDIT.\n")
        f.write(" *\n")
        f.write(" * Wide SonSon level-1 BG: %d cols x %d rows, %d deduped 4bpp tiles\n"
                % (cols, rows, n_tiles))
        f.write(" * (%d bytes VRAM). Tile base = %d. Source: %s\n"
                % (n_tiles * 32, base, cap.get("source", "arcade demo")))
        f.write(" * Method: %s\n" % cap.get("method", ""))
        f.write(" */\n")
        f.write('#include "ss_level.h"\n\n')

        f.write("const u32 ss_level_tiles[SS_LEVEL_TILE_COUNT * 8] = {\n")
        for ti in range(n_tiles):
            longs = tiles[ti * 8: ti * 8 + 8]
            f.write("    /* tile %4d */ %s,\n"
                    % (ti, ",".join("0x%08X" % w for w in longs)))
        f.write("};\n\n")

        f.write("const u16 ss_level_map[SS_LEVEL_COLS * SS_LEVEL_ROWS] = {\n")
        for row in range(rows):
            chunk = nametable[row * cols: row * cols + cols]
            f.write("    " + ",".join("0x%04X" % w for w in chunk) +
                    ",  /* row %2d */\n" % row)
        f.write("};\n")


def emit_multi(caps, levels, base, rows, out_c, out_h):
    """Emit a COMBINED ss_level.c/.h holding N levels, ALL CO-RESIDENT in VRAM, for
    the SEAMLESS SINGLE-RIBBON scroll engine.

    `levels` is a list of dicts: { 'tiles':[u32], 'map':[u16], 'cols':int,
    'n_tiles':int, 'cap':<capture-json>, 'base':int } -- one per captured level.
    Each level is baked at its OWN DISTINCT VRAM tile base (l['base'] = `base` +
    sum(prior tileCounts)), so its nametable words are absolute to that base and all
    8 tilesets can be loaded simultaneously (game_init loads every level's tiles at
    its base -- no per-seam DMA, inherently tear-free). The 8 levels form ONE logical
    ribbon (total width SS_RIBBON_COLS); the streamer maps a ribbon column to (level,
    local col) and reads that level's map directly. See game.c. """
    n = len(levels)
    max_cols = max(l["cols"] for l in levels)
    max_tiles = max(l["n_tiles"] for l in levels)
    total_tiles = sum(l["n_tiles"] for l in levels)
    top = base + total_tiles                    # one past the last level tile
    ribbon_cols = sum(l["cols"] for l in levels)

    with open(out_h, "w", newline="\n") as f:
        f.write("""/* ss_level.h -- GENERATED by tools/gen_level.py --multi.  DO NOT EDIT.
 *
 * SonSon (Capcom, 1984) -- %d DISTINCT wide levels, baked to native Genesis 4bpp
 * tiles + wide nametables, ALL CO-RESIDENT in VRAM for the SEAMLESS SINGLE-RIBBON
 * scroll engine. Each level is reconstructed from REAL GAMEPLAY (md=02 -- the CLEAN
 * playfield, NOT the md=01 attract demo), by pinning the arcade level index $0067
 * and stitching the 32-col videoram window across the scroll sweep
 * (tools/ss_level_cap2.lua). Palettes are the verbatim arcade PAL0 (chars) used by
 * ss_gfx; tiles bake byte-identically via gen_assets.bake_char_tile.
 *
 * SEAMLESS RIBBON (matches the arcade's one endless LOOPING ribbon, RE'd in
 * tools/LEVEL_END_SPEC.md): the 8 levels are concatenated into ONE logical map of
 * SS_RIBBON_COLS columns. Every level has its OWN VRAM tile base (SsLevel.tileBase),
 * so its map words are absolute and ALL 8 tilesets are loaded at once (game_init)
 * -> no runtime tile reload at a seam -> inherently tear-free. The streamer maps a
 * ribbon column to (level, local col) and DMAs that level's map column; the ribbon
 * wraps after the last level back to the first. One contiguous tile block:
 * [SS_LEVEL_TILE_BASE .. SS_LEVEL_TILE_TOP), placed ABOVE the anim tiles and below
 * the SGDK font. See game.c (stream_column / ribbon_locate / game_init).
 */
#ifndef SS_LEVEL_H
#define SS_LEVEL_H

#include <genesis.h>

""" % n)
        f.write("#define SS_LEVEL_COUNT      %d\n" % n)
        f.write("#define SS_LEVEL_ROWS       %d\n" % rows)
        f.write("/* Base VRAM tile index of the ALL-RESIDENT level tile block. Each\n"
                " * level's tiles sit at its own SsLevel.tileBase >= this; every map\n"
                " * word is ABSOLUTE (already includes that level's base). */\n")
        f.write("#define SS_LEVEL_TILE_BASE  %d\n" % base)
        f.write("/* One past the last level tile (block = [BASE .. TOP)). The 8 tilesets\n"
                " * total %d tiles -> they live below the SGDK font (~1376). */\n"
                % total_tiles)
        f.write("#define SS_LEVEL_TILE_TOP   %d\n" % top)
        f.write("/* Total columns in the concatenated ribbon (sum of all level widths).\n"
                " * Ribbon pixel width = SS_RIBBON_COLS * 8; the ribbon LOOPS at it. */\n")
        f.write("#define SS_RIBBON_COLS      %d\n" % ribbon_cols)
        f.write("/* Largest per-level tile working set + widest level (fixed-size sizing). */\n")
        f.write("#define SS_LEVEL_MAX_TILES  %d\n" % max_tiles)
        f.write("#define SS_LEVEL_MAX_COLS   %d\n" % max_cols)
        f.write("\n")
        f.write("/* One level (a ribbon SEGMENT): its deduped 4bpp tiles + count, its\n"
                " * DISTINCT VRAM tile base, the wide ROW-MAJOR nametable (map[row*cols\n"
                " * + col], words absolute to tileBase) and its width in BG columns. */\n")
        f.write("typedef struct {\n")
        f.write("    const u32 *tiles;     /* tileCount*8 longs, load at .tileBase          */\n")
        f.write("    u16        tileCount; /* distinct deduped 8x8 tiles                    */\n")
        f.write("    const u16 *map;       /* cols*SS_LEVEL_ROWS words, row-major, absolute */\n")
        f.write("    u16        cols;      /* level width in BG columns (pixel width = *8)  */\n")
        f.write("    u16        tileBase;  /* this level's VRAM tile base (all co-resident) */\n")
        f.write("} SsLevel;\n\n")
        f.write("extern const SsLevel ss_levels[SS_LEVEL_COUNT];\n")
        f.write("/* Ribbon prefix sums: ss_ribbon_col0[i] = first ribbon column of level i\n"
                " * (ss_ribbon_col0[SS_LEVEL_COUNT] == SS_RIBBON_COLS). Lets the streamer\n"
                " * map a ribbon column to its level + local column. */\n")
        f.write("extern const u16 ss_ribbon_col0[SS_LEVEL_COUNT + 1];\n")
        f.write("\n#endif /* SS_LEVEL_H */\n")

    with open(out_c, "w", newline="\n") as f:
        f.write("/* ss_level.c -- GENERATED by tools/gen_level.py --multi.  DO NOT EDIT.\n")
        f.write(" *\n * %d distinct SonSon levels, ALL CO-RESIDENT (seamless ribbon),\n"
                " * tile block [%d .. %d):\n" % (n, base, top))
        c0 = 0
        for i, l in enumerate(levels):
            f.write(" *   level %d: %3d cols x %d rows, %3d tiles (%d B VRAM) @ base %4d, ribbon cols %d..%d  src: %s\n"
                    % (i + 1, l["cols"], rows, l["n_tiles"], l["n_tiles"] * 32,
                       l["base"], c0, c0 + l["cols"] - 1,
                       l["cap"].get("source", "arcade md=02")))
            c0 += l["cols"]
        f.write(" * ribbon width = %d cols (%d px), loops back to level 1 after level %d.\n"
                % (ribbon_cols, ribbon_cols * 8, n))
        f.write(" */\n")
        f.write('#include "ss_level.h"\n\n')

        for i, l in enumerate(levels):
            tiles = l["tiles"]; nt = l["n_tiles"]
            f.write("static const u32 ss_level%d_tiles[%d * 8] = {\n" % (i + 1, nt))
            for ti in range(nt):
                longs = tiles[ti * 8: ti * 8 + 8]
                f.write("    %s,\n" % ",".join("0x%08X" % w for w in longs))
            f.write("};\n\n")
            cols = l["cols"]; nm = l["map"]
            f.write("static const u16 ss_level%d_map[%d * SS_LEVEL_ROWS] = {\n" % (i + 1, cols))
            for row in range(rows):
                chunk = nm[row * cols: row * cols + cols]
                f.write("    " + ",".join("0x%04X" % w for w in chunk) +
                        ",  /* row %2d */\n" % row)
            f.write("};\n\n")

        f.write("const SsLevel ss_levels[SS_LEVEL_COUNT] = {\n")
        for i, l in enumerate(levels):
            f.write("    { ss_level%d_tiles, %d, ss_level%d_map, %d, %d },\n"
                    % (i + 1, l["n_tiles"], i + 1, l["cols"], l["base"]))
        f.write("};\n\n")

        # Ribbon column prefix sums (first ribbon column of each level; last entry
        # = total ribbon width). Lets the streamer/collision map ribbon col -> level.
        f.write("const u16 ss_ribbon_col0[SS_LEVEL_COUNT + 1] = {\n    ")
        acc = 0
        parts = []
        for l in levels:
            parts.append(str(acc)); acc += l["cols"]
        parts.append(str(acc))
        f.write(", ".join(parts) + "\n};\n")


def main_multi(argv):
    """gen_level.py --multi <cap1> <cap2> ... [--base N] [--blank-top N]"""
    arcade_dir = os.path.join(G.REPO, "arcade")
    out_c = os.path.join(G.REPO, "src", "ss_level.c")
    out_h = os.path.join(G.REPO, "inc", "ss_level.h")
    # ALL-8-RESIDENT: the 8 level tilesets are co-resident in ONE contiguous VRAM
    # block placed ABOVE the anim tiles (SS_ANIM_TILE_BASE=346, 216 tiles -> 346..561)
    # and below the SGDK font (~1376). Block starts at 562; the 8 levels sum to ~645
    # tiles -> 562..1206, leaving headroom. (Anim base is unchanged, so ss_anim.c
    # need NOT be regenerated.) See game.c game_init / the seamless-ribbon streamer.
    base = 562
    blank_top = 5
    caps = []
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--arcade":     arcade_dir = argv[i + 1]; i += 2
        elif a == "--out-c":    out_c = argv[i + 1]; i += 2
        elif a == "--out-h":    out_h = argv[i + 1]; i += 2
        elif a == "--base":     base = int(argv[i + 1]); i += 2
        elif a == "--blank-top": blank_top = int(argv[i + 1]); i += 2
        elif a.startswith("--"): sys.exit("unknown option %s" % a)
        else: caps.append(a); i += 1
    if not caps:
        sys.exit("--multi needs at least one capture json")

    roms = G.Roms(arcade_dir)
    levels = []
    rows = None
    # ALL-8-RESIDENT seamless ribbon: every level gets a DISTINCT VRAM tile base so
    # all 8 tilesets can be co-resident; each level's nametable words are baked
    # absolute to ITS OWN base. Level i base = `base` + sum(tileCount[0..i-1]).
    # We bake each level twice-implicitly: first at base 0 just to learn tileCount,
    # then re-bake the nametable at the real cumulative base. (assemble_level adds
    # base+local into each word, so we re-run it with the computed base.)
    cur_base = base
    for cp in caps:
        with open(cp) as f:
            cap = json.load(f)
        # learn tile count (base-independent: dedup is on baked bytes)
        tiles0, _, cols, rws, n_tiles, n_combos = assemble_level(
            roms, cap, cur_base, blank_top)
        # re-bake nametable at this level's real base (tiles bytes are identical)
        tiles, nametable, cols, rws, n_tiles, _ = assemble_level(
            roms, cap, cur_base, blank_top)
        rows = rws
        levels.append({"tiles": tiles, "map": nametable, "cols": cols,
                       "n_tiles": n_tiles, "cap": cap, "base": cur_base})
        print("  level %d: %d cols, %d combos -> %d tiles (%d B, %.1f%% VRAM) @ base %d"
              % (len(levels), cols, n_combos, n_tiles, n_tiles * 32,
                 100.0 * n_tiles / 2048, cur_base))
        cur_base += n_tiles

    os.makedirs(os.path.dirname(out_c), exist_ok=True)
    os.makedirs(os.path.dirname(out_h), exist_ok=True)
    emit_multi(caps, levels, base, rows, out_c, out_h)

    total = sum(l["n_tiles"] for l in levels)
    top = base + total
    ribbon_cols = sum(l["cols"] for l in levels)
    print("gen_level --multi: %d levels (ALL-RESIDENT seamless ribbon)" % len(levels))
    print("  all-8-resident block    : tiles %d..%d (%d tiles, %d B, %.1f%% VRAM)"
          % (base, top - 1, total, total * 32, 100.0 * total / 2048))
    print("  ribbon width            : %d cols (%d px)" % (ribbon_cols, ribbon_cols * 8))
    print("  per-level bases         : %s" % ", ".join(str(l["base"]) for l in levels))
    print("  block start base index  : %d  (top tile %d; SGDK font ~1376)" % (base, top - 1))
    print("  wrote", out_c)
    print("  wrote", out_h)


def main(argv):
    if argv and argv[0] == "--multi":
        return main_multi(argv[1:])
    cap_path = os.path.join(HERE, "level1_capture.json")
    arcade_dir = os.path.join(G.REPO, "arcade")
    out_c = os.path.join(G.REPO, "src", "ss_level.c")
    out_h = os.path.join(G.REPO, "inc", "ss_level.h")
    base = 0
    blank_top = 0

    args = list(argv); i = 0
    while i < len(args):
        a = args[i]
        if a == "--arcade":   arcade_dir = args[i + 1]; i += 2
        elif a == "--out-c":  out_c = args[i + 1]; i += 2
        elif a == "--out-h":  out_h = args[i + 1]; i += 2
        elif a == "--base":   base = int(args[i + 1]); i += 2
        elif a == "--blank-top": blank_top = int(args[i + 1]); i += 2
        elif a.startswith("--"): sys.exit("unknown option %s" % a)
        else: cap_path = a; i += 1

    roms = G.Roms(arcade_dir)
    with open(cap_path) as f:
        cap = json.load(f)

    tiles, nametable, cols, rows, n_tiles, n_combos = assemble_level(
        roms, cap, base, blank_top)

    os.makedirs(os.path.dirname(out_c), exist_ok=True)
    os.makedirs(os.path.dirname(out_h), exist_ok=True)
    emit(cap, tiles, nametable, cols, rows, n_tiles, base, out_c, out_h)

    print("gen_level: wide level %d cols x %d rows" % (cols, rows))
    print("  char (code,bank) used : %d -> %d distinct 8x8 tiles (deduped)"
          % (n_combos, n_tiles))
    print("  baked tile bytes      : %d  (%.0f%% of 2048-tile VRAM)"
          % (n_tiles * 32, 100.0 * n_tiles / 2048))
    print("  tile base index       : %d" % base)
    print("  level pixel width      : %d px (%d cols * 8)" % (cols * 8, cols))
    print("  wrote", out_c)
    print("  wrote", out_h)


if __name__ == "__main__":
    main(sys.argv[1:])
