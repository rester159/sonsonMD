#!/usr/bin/env python3
"""Bake both A807 end-marker poses into the eight-tile F700 arena."""
from pathlib import Path
import hashlib,json
import gen_assets as G
r=Path(__file__).resolve().parents[1];g=G.Roms(str(r/'arcade'))
rom=b''.join((r/'arcade'/n).read_bytes()for n in ('ss.01e','ss.02e','ss.03e'))
assert hashlib.sha256(rom).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
pixels=[]
for pose in range(2):
 p=rom[0x681f+pose*8:0x6827+pose*8]
 for k in range(4):
  a=p[k+4];pixels.extend(G.bake_char_tile(g,p[k]+((a&3)<<8),a>>2))
(r/'src/arcade_finish_art.c').write_text('/* Generated by tools/gen_arcade_finish_art.py. */\n#include "arcade_finish_art.h"\nconst u32 arcade_finish_pixels[8*8]={\n'+''.join(','.join('0x%08x'%v for v in pixels[i:i+8])+',\n'for i in range(0,64,8))+'};\nconst u16 arcade_finish_tiles[2][4]={{1976,1977,1978,1979},{1980,1981,1982,1983}};\n')
o=r/'out/parity-audit/finish-art';o.mkdir(parents=True,exist_ok=True)
(o/'manifest.json').write_text(json.dumps({'tiles':8,'vram_start':0xf700,'vram_end':0xf800,'source':'A81F/A827; A807 writes10F4,10D4,10F5,10D5'},indent=2)+'\n')
