#!/usr/bin/env python3
"""Extract A1F0 grid, 0217..0219 labels, and 9FF9 cursor graphics."""
from pathlib import Path
import hashlib,json
import gen_assets as G
r=Path(__file__).resolve().parents[1]
rom=b''.join((r/'arcade'/n).read_bytes() for n in ('ss.01e','ss.02e','ss.03e'))
assert hashlib.sha256(rom).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
g=G.Roms(str(r/'arcade'))
def byte(a):return rom[a-0x4000]
def word(a):return byte(a)*256+byte(a+1)
tiles=[];cells=[];groups=[]
def tile(code,attr):
 p=G.bake_char_tile(g,code+((attr&3)<<8),attr>>2)
 if p not in tiles:tiles.append(p)
 return tiles.index(p)
blank=tile(16,0)
glyphs=[tile(code,0x2c) for code in range(64)]
for row in range(5):
 for col in range(17):
  cells.append((word(0xa212)-0x1000+row*64+col,tile(byte(0xa214+row*17+col),0x2c)))
groups.append((0,len(cells)))
for command in (23,24,25):
 p=word(0x4821+command*2);first=len(cells)
 while True:
  addr,attr=word(p),byte(p+2);p+=3
  while True:
   code=byte(p);p+=1
   if not code:continue
   if code in (47,63):break
   cells.append((addr-0x1000,tile((code-48)&255,attr)));addr+=1
  if code==63:break
 groups.append((first,len(cells)-first))
cursor=len(tiles)
for code,attr in ((0x56,0xc3),(0x57,0xc0)):
 pixels=G.bake_sprite_tiles(g,code,attr&31)
 tiles.extend(tuple(pixels[i:i+8]) for i in range(0,32,8))
assert len(tiles)<=132, 'Name entry exceeds the shared bonus-art arena'
h='''/* Generated by tools/gen_name_art.py. */
#ifndef ARCADE_NAME_ART_H
#define ARCADE_NAME_ART_H
#include "arcade_types.h"
typedef struct {u16 cell,tile;} ArcadeNameCell;
typedef struct {u16 first,count;} ArcadeNameGroup;
'''
h+=f'#define ARCADE_NAME_TILES {len(tiles)}\n#define ARCADE_NAME_CELLS {len(cells)}\n#define ARCADE_NAME_BLANK {blank}\n#define ARCADE_NAME_CURSOR {cursor}\n'
h+='''extern const u32 arcade_name_pixels[ARCADE_NAME_TILES*8];
extern const u16 arcade_name_glyphs[64];
extern const ArcadeNameCell arcade_name_cells[ARCADE_NAME_CELLS];
/* Grid, instruction, P1 label, P2 label. */
extern const ArcadeNameGroup arcade_name_groups[4];
#endif
'''
s='/* Generated by tools/gen_name_art.py. */\n#include "arcade_name_art.h"\n'
s+='const u32 arcade_name_pixels[ARCADE_NAME_TILES*8]={\n'+''.join(','.join(f'0x{v:08x}' for v in t)+',\n' for t in tiles)+'};\n'
s+='const u16 arcade_name_glyphs[64]={'+','.join(map(str,glyphs))+'};\n'
s+='const ArcadeNameCell arcade_name_cells[ARCADE_NAME_CELLS]={'+','.join('{%d,%d}'%c for c in cells)+'};\n'
s+='const ArcadeNameGroup arcade_name_groups[4]={'+','.join('{%d,%d}'%v for v in groups)+'};\n'
(r/'inc/arcade_name_art.h').write_text(h);(r/'src/arcade_name_art.c').write_text(s)
o=r/'out/parity-audit/name-art';o.mkdir(parents=True,exist_ok=True)
report={'tiles':len(tiles),'cells':len(cells),'groups':groups,'cursor_tile':cursor,'scope':'Source grid/labels and fixed cursor sprites only; display and gameplay ownership pending.'}
(o/'manifest.json').write_text(json.dumps(report,indent=2)+'\n');print(report)
