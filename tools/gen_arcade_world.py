#!/usr/bin/env python3
"""Decode all 26 original segment descriptors and collision masks, not screenshots.
Main MC6809 fixed/code ROM $6485, $653B, $6D3B, $825B; revision ss.01e/02e/03e.
$A6C9/$A6FB select paired columns; $916A writes bottom-up from row 31,
whose first byte is the permanent blank; 13 macros occupy rows 30 down to 5.
"""
from pathlib import Path
import hashlib,json,re
import gen_assets as G
r=Path(__file__).resolve().parents[1];rom=b''.join((r/'arcade'/f).read_bytes()for f in ['ss.01e','ss.02e','ss.03e'])
anim=(r/'inc/ss_anim.h').read_text()
base=max(562,sum(int(re.search(r'#define '+n+r'\s+(\d+)',anim)[1])for n in ['SS_ANIM_TILE_BASE','SS_ANIM_TILE_COUNT']))
def u8(a):
 assert 0x4000<=a<0x10000
 return rom[a-0x4000]
def u16(a):return (u8(a)<<8)|u8(a+1)
g=G.Roms(str(r/'arcade'));tiles=[(0,)*8];lookup={tiles[0]:0};levels=[];col0=[0];events=[]
for stage in range(26):
 rec=0x6485+stage*7;duration=u8(rec);bg=u16(rec+3);collision=u16(rec+5);cols=duration*32
 assert bg==0x6D3B+stage*208 and collision==0x825B+stage*128
 chars=[[(16,0)]*32 for _ in range(32)]
 for x in range(32):
  for k in range(13):
   macro=u8(bg+(x//2)*13+k);a=0x653B+macro*8+(x%2)*2
   for half in range(2):chars[30-k*2-half][x]=(u8(a+half),u8(a+half+4))
 pattern=[]
 for y in range(32):
  for x in range(32):
   code,attr=chars[y][x]
   t=tuple(G.bake_char_tile(g,code+((attr&3)<<8),attr>>2)) if y>=5 else tiles[0]
   if t not in lookup:lookup[t]=len(tiles);tiles.append(t)
   pattern.append(base+lookup[t] if y>=5 else 0)
 worldmap=[pattern[y*32+x%32]for y in range(32)for x in range(cols)]
 masks=[]
 for x in range(cols):
  mask=0
  for tier in range(6):
   row=4+tier*4
   if u8(collision+(x%32)*4+(row>>3))&(128>>(row&7)):mask|=1<<tier
  masks.append(mask)
 levels.append((cols,worldmap,masks));events.append(u8(rec+1));col0.append(col0[-1]+cols)
assert col0[-1]==2784 and base+len(tiles)<=1376,(len(tiles),col0[-1])
h='''/* GENERATED by tools/gen_arcade_world.py from original segment descriptors. */
#ifndef SS_LEVEL_H
#define SS_LEVEL_H
#include <genesis.h>
'''
for name,value in [('SS_LEVEL_COUNT',26),('SS_LEVEL_ROWS',32),('SS_LEVEL_TILE_BASE',base),('SS_LEVEL_TILE_TOP',base+len(tiles)),('SS_RIBBON_COLS',2784),('SS_LEVEL_MAX_TILES',len(tiles)),('SS_LEVEL_MAX_COLS',160)]:h+=f'#define {name} {value}\n'
h+='''/* All maps share one exact-tile dictionary. Only descriptor zero loads it;
 * tileCount==0 on later segments means already resident, never a zero DMA. */
typedef struct {const u32 *tiles;u16 tileCount;const u16 *map;u16 cols;u16 tileBase;} SsLevel;
extern const SsLevel ss_levels[SS_LEVEL_COUNT];
extern const u16 ss_ribbon_col0[SS_LEVEL_COUNT+1];
extern const u8 ss_segment_event[SS_LEVEL_COUNT];
#endif
'''
(r/'inc/ss_level.h').write_text(h)
s='/* GENERATED by tools/gen_arcade_world.py. Complete 87-screen arcade ribbon. */\n#include "ss_level.h"\nstatic const u32 world_tiles[%d*8]={\n'%len(tiles)
s+=''.join('    '+','.join('0x%08X'%v for v in t)+',\n'for t in tiles)+'};\n'
for i,(cols,worldmap,masks)in enumerate(levels):
 s+=f'static const u16 world_map_{i}[{cols}*32]={{\n'
 s+=''.join('    '+','.join('0x%04X'%v for v in worldmap[y*cols:(y+1)*cols])+',\n'for y in range(32))+'};\n'
s+='const SsLevel ss_levels[SS_LEVEL_COUNT]={\n'+''.join(f'    {{world_tiles,{len(tiles) if i==0 else 0},world_map_{i},{lev[0]},{base}}},\n'for i,lev in enumerate(levels))+'};\n'
s+='const u16 ss_ribbon_col0[SS_LEVEL_COUNT+1]={'+','.join(map(str,col0))+'};\n'
s+='const u8 ss_segment_event[SS_LEVEL_COUNT]={'+','.join(map(str,events))+'};\n';(r/'src/ss_level.c').write_text(s)
h='''/* GENERATED by tools/gen_arcade_world.py: original $825B collision bitmaps. */
#ifndef SS_COLLISION_H
#define SS_COLLISION_H
#include <genesis.h>
#include "ss_level.h"
#define SS_COLLISION_TIERS 6
extern const s16 SS_TIER_Y[6];
extern const u8 SS_TIER_FLOOR_ROW[6];
extern const u8 ss_ribbon_collision[SS_RIBBON_COLS];
extern const u8 *const ss_collision[SS_LEVEL_COUNT];
extern const u16 ss_collision_cols[SS_LEVEL_COUNT];
#endif
''';(r/'inc/ss_collision.h').write_text(h)
s='#include "ss_collision.h"\nconst s16 SS_TIER_Y[6]={200,168,136,104,72,40};\nconst u8 SS_TIER_FLOOR_ROW[6]={27,23,19,15,11,7};\n'
for i,(cols,_,masks)in enumerate(levels):s+=f'static const u8 masks_{i}[{cols}]={{'+','.join('0x%02X'%v for v in masks)+'};\n'
s+='const u8 ss_ribbon_collision[SS_RIBBON_COLS]={'+','.join('0x%02X'%m for _,_,masks in levels for m in masks)+'};\n'
s+='const u8 *const ss_collision[SS_LEVEL_COUNT]={'+','.join(f'masks_{i}'for i in range(26))+'};\n'
s+='const u16 ss_collision_cols[SS_LEVEL_COUNT]={'+','.join(str(v[0])for v in levels)+'};\n';(r/'src/ss_collision.c').write_text(s)
report={'program_sha256':hashlib.sha256(rom).hexdigest(),'segments':26,'columns':col0[-1],'pixels':col0[-1]*8,'resident_tiles':len(tiles),'tile_top':base+len(tiles),'durations':[v[0]//32 for v in levels],'events':events,'collision_source':'Original ROM masks, not visual floor heuristics'}
o=r/'out/parity-audit';o.mkdir(parents=True,exist_ok=True);(o/'world-extraction.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report,indent=2))
