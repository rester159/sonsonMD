#!/usr/bin/env python3
"""Flatten original four-cell large-enemy animation into native frame records."""
from pathlib import Path
import hashlib,json
r=Path(__file__).resolve().parents[1];b=(r/'arcade/ss.03e').read_bytes()
assert hashlib.sha256(b''.join((r/'arcade'/n).read_bytes()for n in('ss.01e','ss.02e','ss.03e'))).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
def get(a,n):assert 0xc000<=a and a+n<=0x10000;return b[a-0xc000:a-0xc000+n]
def word(a):return int.from_bytes(get(a,2),'big')
roots=[0xd5ce,0xd848,0xd8bc]+[word(t+i*2)for t in(0xd987,0xd997)for i in range(8)]
frames={}
def visit(a):
 if a in frames:return
 raw=get(a,5);n=word(a+5)if raw[4]&128 else a+5
 frames[a]=(list(raw[:4]),raw[4]&127,n);visit(n)
for a in roots:visit(a)
addresses=sorted(frames)
score_roots=[word(0xd8a0+i*2)for i in range(12)]
for a in score_roots:
 if a not in frames:
  raw=get(a,5);assert raw[4]==255
  # Score lifetime is only 12 updates, before this 127-count timer expires.
  # The source's following pointer is never dereferenced in that lifetime.
  frames[a]=(list(raw[:4]),127,a);addresses.append(a)
ids={a:i for i,a in enumerate(addresses)}
s='/* Generated by tools/gen_arcade_large_animation.py; semantic four-cell frames. */\n#include "arcade_large.h"\nconst ArcadeLargeFrame arcade_large_frames[]={\n'
for a in addresses:
 codes,t,n=frames[a];s+='    {%d,%d,{%s}},\n'%(ids[n],t,','.join(str(x)for x in codes))
s+='};\nconst u16 arcade_large_walk[2][8]={\n'
for base in(0xd997,0xd987):s+='    {'+','.join(str(ids[word(base+i*2)])for i in range(8))+'},\n'
s+='};\nconst u16 arcade_large_entry=%d,arcade_large_exit=%d,arcade_large_death=%d;\n'%(ids[0xd5ce],ids[0xd848],ids[0xd8bc])
s+='const u16 arcade_large_score[4][3]={\n'
for v in range(4):s+='    {'+','.join(str(ids[a])for a in score_roots[v*3:v*3+3])+'},\n'
s+='};\n'
(r/'src/arcade_large_animation_data.c').write_text(s)
o=r/'out/parity-audit';o.mkdir(parents=True,exist_ok=True);(o/'large-animation-map.json').write_text(json.dumps({'addresses':addresses,'roots':roots,'score_roots':score_roots},indent=2)+'\n')
print(len(addresses),'four-cell frames')
