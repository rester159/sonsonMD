#!/usr/bin/env python3
"""Extract the final-section flash and record the source results transition."""
from pathlib import Path
import hashlib,json
r=Path(__file__).resolve().parents[1]
rom=b''.join((r/'arcade'/n).read_bytes()for n in ('ss.01e','ss.02e','ss.03e'))
sha=hashlib.sha256(rom).hexdigest()
assert sha=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
patterns=[rom[0x681f:0x6827],rom[0x6827:0x682f]]
assert patterns==[bytes.fromhex('c6c4c7c54c4c4c4c'),bytes.fromhex('c6c4c7c5b8b8b8b8')]
(r/'src/arcade_finish_data.c').write_text('/* Generated by tools/gen_arcade_finish.py. */\n#include "arcade_finish.h"\nconst u8 arcade_finish_patterns[2][8]={\n'+''.join('{'+','.join('0x%02x'%v for v in p)+'},\n'for p in patterns)+'};\n')
def pointers(address,count):
 return [int.from_bytes(rom[address-0x4000+i*2:address-0x4000+i*2+2],'big')for i in range(count)]
report={'schema':1,'source_sha256':sha,'gate':0xa7f0,'flash':0xa807,
 'destination':0x10f4,'patterns':[list(p)for p in patterns],
 'expiry_writes':{'00A5':0,'0008':4,'000B':0,'000E':0},
 'results_substates':pointers(0x9801,3),
 'settle_substates':pointers(0x980f,3),
 'screen_load_substates':pointers(0x983d,2),
 'presentation_substates':pointers(0x9869,7),
 'scope':'Static source extraction. Results settle calls normal gameplay until clock&63==0; next phase waits on source screen-command completion; presentation remains to be implemented.'}
assert report['results_substates']==[0x9807,0x9835,0x9861]
assert report['presentation_substates']==[0x9877,0x9898,0x98df,0x992c,0x9989,0x99e9,0x9a18]
decor=[]
for i in range(3):
 a=0x9962-0x4000+i*5
 root=int.from_bytes(rom[a:a+2],'big')
 x=int.from_bytes(rom[a+2:a+4],'big');y=rom[a+4]
 frames=[];cursor=root
 while True:
  p=cursor-0x4000;code,attr,timer=rom[p:p+3]
  frames.append({'source':cursor,'code':code,'attr':attr,'timer':timer&127,
                 'display_updates':(timer&127)+1})
  if timer&128:
   assert int.from_bytes(rom[p+3:p+5],'big')==root
   break
  cursor+=3
  assert len(frames)<16
 decor.append({'root':root,'x':x,'y':y,'frames':frames})
assert [d['x']for d in decor]==[144,80,112]
assert all([f['timer']for f in d['frames']]==[10,16]for d in decor)
report['decorations']=decor
report['restart']={'increment_byte':'007E','clear_bytes':['0067','0065','0066'],
                   'sound_event':0x12,'next_state':1}
o=r/'out/parity-audit/finish';o.mkdir(parents=True,exist_ok=True)
(o/'source-contract.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
