#!/usr/bin/env python3
"""Extract A893's immutable background patterns from the fixed arcade revision."""
from pathlib import Path
import hashlib
r=Path(__file__).resolve().parents[1]
rom=b''.join((r/'arcade'/f).read_bytes() for f in ('ss.01e','ss.02e','ss.03e'))
assert hashlib.sha256(rom).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
patterns=[rom[0x68e2+i*8:0x68ea+i*8] for i in range(8)]
destinations=[int.from_bytes(rom[0x6922+i*2:0x6924+i*2],'big') for i in range(6)]
assert destinations==[0x139e,0x131e,0x129e,0x121e,0x119e,0x111e]
(r/'src/arcade_release_data.c').write_text(
    '/* Generated by tools/gen_arcade_release.py. */\n#include "arcade_release.h"\n'
    'const u8 arcade_release_patterns[8][8]={\n'+
    ''.join('    {'+','.join('0x%02x'%b for b in p)+'},\n' for p in patterns)+
    '};\nconst u16 arcade_release_destinations[6]={'+
    ','.join('0x%04x'%v for v in destinations)+'};\n')
