#!/usr/bin/env python3
"""Extract fixed MC6809 $6485 section timing, ss.01e/02e/03e revision."""
from pathlib import Path
import hashlib
r=Path(__file__).resolve().parents[1]
rom=b''.join((r/'arcade'/f).read_bytes() for f in ('ss.01e','ss.02e','ss.03e'))
assert hashlib.sha256(rom).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
rows=[tuple(rom[0x2485+i*7:0x2488+i*7]) for i in range(26)]
assert sum(x[0] for x in rows)==87
(r/'src/arcade_section_data.c').write_text('/* Generated by tools/gen_arcade_sections.py. */\n#include "arcade_section.h"\nconst ArcadeSectionDescriptor arcade_sections[26]={\n'+''.join('    {%d,%d,%d},\n'%x for x in rows)+'};\n')
