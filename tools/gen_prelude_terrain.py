#!/usr/bin/env python3
"""935F/907D: initial32 collision columns from the first segment descriptor."""
import hashlib
from pathlib import Path
r=Path(__file__).resolve().parents[1]
rom=b''.join((r/'arcade'/n).read_bytes()for n in ('ss.01e','ss.02e','ss.03e'))
assert hashlib.sha256(rom).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
address=int.from_bytes(rom[0x248a:0x248c],'big')
assert address==0x825b
data=rom[address-0x4000:address-0x4000+128]
s='/* Generated by tools/gen_prelude_terrain.py;935F/907D. */\n#include "arcade_prelude_terrain.h"\nconst u8 arcade_prelude_terrain[128]={\n'
for i in range(0,128,16):s+='    '+','.join('0x%02x'%v for v in data[i:i+16])+',\n'
s+='};\n';(r/'src/arcade_prelude_terrain_data.c').write_text(s)
