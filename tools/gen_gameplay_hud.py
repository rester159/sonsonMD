#!/usr/bin/env python3
"""Source-colored HUD glyphs and reserve-life icons in unused gameplay lowercase font slots."""
from pathlib import Path
import gen_assets as G
r=Path(__file__).resolve().parents[1];rom=G.Roms(str(r/'arcade'))
# a..g encode SONTHIG; h..o encode TOALSCRE for TOTAL SCORE.
# SON/T use source bank3; HIGH/TOTAL SCORE use bank10.
glyphs=[(c,3 if i<4 else 10) for i,c in enumerate('SONTHIGTOALSCRE')]
s='#include "arcade_types.h"\n/* Generated by tools/gen_gameplay_hud.py; source header4821 table. */\nconst u32 arcade_gameplay_label_tiles[23*8]={\n'
for c,b in glyphs:s+=' '+','.join(f'0x{x:08x}' for x in G.bake_char_tile(rom,ord(c)-ord('A')+17,b))+',\n'
# 5250/5258: bottom attributes, top attributes, bottom codes, top codes.
b=(r/'arcade/ss.01e').read_bytes()
assert b[0x1250:0x1260].hex()=='99999595f4f5e4e59f9f9f9f7c7d7a7b'
for owner in range(2):
 pattern=b[0x1250+owner*8:0x1258+owner*8]
 for i in (2,3,0,1):
  attr=pattern[i];code=pattern[i+4]+((attr&3)<<8)
  s+=' '+','.join(f'0x{x:08x}' for x in G.bake_char_tile(rom,code,attr>>2))+',\n'
s+='};\n';(r/'src/arcade_gameplay_label_art.c').write_text(s)
