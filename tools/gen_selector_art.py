#!/usr/bin/env python3
"""gen_selector_art.py -- bake the SELECT GAME screen art (tools/selector_art/)
into native Genesis tiles + tilemaps + palettes for src/game_select.c.
Emits src/selector_art.c + inc/selector_art.h with selector_art_* symbols.

Sources are already clean art on pure black (made with gpt-image from the
original cover scans, arcade_flyer.png / home_box.webp, owner-approved):
  sonson_logo_clean.png   SONSON logo (O counters show the magenta shadow)
  sonson2_logo_clean.png  SON SON II logo
  collection_title.png    "The SonSon Collection" title (style C)
Anything brighter than black is logo; black -> index 0 (transparent, the
backdrop shows). Each asset is cropped to its pixels and scaled to fit its
box, centred: both game logos get the SAME 144x80 box (18x10 tiles), the
title a 240x72 box (30x9 tiles). Then reduced to Genesis colour: every
channel snapped to the 3-bit VDP DAC ladder, median-cut colours from the
asset's own pixels, no dithering. The title uses 14 colours because it
shares its palette line with the selection frame (index 15 = frame red).
Identical tiles are shared per asset."""
import os
import numpy as np
from PIL import Image
from scipy import ndimage as nd

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
ART  = os.path.join(HERE, "selector_art")

LV = [0, 52, 87, 116, 144, 172, 206, 255]          # Genesis DAC levels (3 bits/channel)
FRAME_RED = 0x000E                                 # title line index 15 (game_select.c)

ASSETS = [  # (symbol, source, box in tiles, colours, fixed index 15 or None)
    ("sonson",  "sonson_logo_clean.png",  (18, 10), 15, None),
    ("sonson2", "sonson2_logo_clean.png", (18, 10), 15, None),
    ("title",   "collection_title.png",   (30, 9),  14, FRAME_RED),
]

def lvl(v): return min(range(8), key=lambda i: abs(LV[i] - v))
def cram(rgb): return lvl(rgb[2]) << 9 | lvl(rgb[1]) << 5 | lvl(rgb[0]) << 1

def plug(on, a, most=8):
    """Fill pinholes (enclosed gaps of < most px) left after scaling, painted
    from the nearest logo pixel."""
    lab, n = nd.label(nd.binary_fill_holes(on) & ~on)
    fix = np.isin(lab, [i for i in range(1, n + 1) if (lab == i).sum() < most])
    _, (iy, ix) = nd.distance_transform_edt(~on, return_indices=True)
    a = a.copy(); a[fix] = a[iy[fix], ix[fix]]
    return on | fix, a

def bake(src, tw, th, ncol, fixed15):
    W, H = tw * 8, th * 8
    a = np.array(Image.open(os.path.join(ART, src)).convert("RGB"))
    m = a.max(axis=2) > 60                          # not black -> logo
    ys, xs = np.nonzero(m)
    x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    a[~m] = 0
    s = min(W / (x1 - x0), H / (y1 - y0))           # fit the box, keep aspect
    sw, sh = round((x1 - x0) * s), round((y1 - y0) * s)
    logo = Image.fromarray(a[y0:y1, x0:x1]).resize((sw, sh), Image.LANCZOS)
    mask = Image.fromarray((m[y0:y1, x0:x1] * 255).astype(np.uint8)).resize((sw, sh), Image.LANCZOS)
    im = Image.new("RGB", (W, H)); im.paste(logo, ((W - sw) // 2, (H - sh) // 2))
    mk = Image.new("L", (W, H)); mk.paste(mask, ((W - sw) // 2, (H - sh) // 2))
    on, im = plug(np.array(mk) >= 128, np.array(im))
    im = Image.fromarray(im).point(lambda v: LV[lvl(v)])   # pre-snap to the 512-colour space
    sample = Image.fromarray(np.array(im)[on][None, :, :])   # logo pixels only
    q = sample.quantize(ncol, method=Image.MEDIANCUT, dither=Image.NONE).getpalette()[:3 * ncol]
    rgb = [tuple(LV[lvl(c)] for c in q[i:i + 3]) for i in range(0, 3 * ncol, 3)]
    p = Image.new("P", (1, 1))
    p.putpalette(sum(rgb, ()) + rgb[0] * (256 - ncol))   # pad with a real entry
    q = np.array(im.quantize(palette=p, dither=Image.NONE))
    px = np.where(on, np.minimum(q, ncol - 1) + 1, 0)    # off-logo -> index 0 (transparent)
    pal = [0x000] + [cram(c) for c in rgb]
    pal += [0x000] * (16 - len(pal))
    if fixed15 is not None:
        pal[15] = fixed15
    tiles, index, tmap = [], {}, []
    for ty in range(th):
        for tx in range(tw):
            t = tuple(
                sum(int(px[ty * 8 + y, tx * 8 + x]) << (28 - 4 * x) for x in range(8))
                for y in range(8))
            if t not in index:
                index[t] = len(tiles); tiles.append(t)
            tmap.append(index[t])
    return pal, tiles, tmap

baked = [(sym, tw, th, *bake(src, tw, th, n, f)) for sym, src, (tw, th), n, f in ASSETS]

h = open(os.path.join(REPO, "inc", "selector_art.h"), "w", newline="\n")
h.write("/* selector_art.h -- GENERATED by tools/gen_selector_art.py. DO NOT EDIT.\n")
h.write(" * SELECT GAME screen art: the SONSON / SON SON II logos (both 18x10 tiles,\n")
h.write(" * 144x80 px) and \"The SonSon Collection\" title (30x9 tiles). One palette\n")
h.write(" * line each, index 0 transparent; the title's index 15 is the frame red. */\n")
h.write("#ifndef SELECTOR_ART_H\n#define SELECTOR_ART_H\n#include <genesis.h>\n")
for sym, tw, th, pal, tiles, tmap in baked:
    S = sym.upper()
    h.write("\n#define SELECTOR_ART_%s_TW  %d   /* tiles */\n" % (S, tw))
    h.write("#define SELECTOR_ART_%s_TH  %d\n" % (S, th))
    h.write("#define SELECTOR_ART_%s_TILE_COUNT  %d\n" % (S, len(tiles)))
    h.write("extern const u16 selector_art_%s_pal[16];\n" % sym)
    h.write("extern const u32 selector_art_%s_tiles[SELECTOR_ART_%s_TILE_COUNT * 8];\n" % (sym, S))
    h.write("extern const u16 selector_art_%s_map[SELECTOR_ART_%s_TW * SELECTOR_ART_%s_TH];  /* local tile ids */\n" % (sym, S, S))
h.write("\n#endif\n")
h.close()

c = open(os.path.join(REPO, "src", "selector_art.c"), "w", newline="\n")
c.write("/* selector_art.c -- GENERATED by tools/gen_selector_art.py. DO NOT EDIT. */\n")
c.write("#include \"selector_art.h\"\n")
for sym, tw, th, pal, tiles, tmap in baked:
    S = sym.upper()
    c.write("\nconst u16 selector_art_%s_pal[16] = {\n    %s\n};\n" % (sym, ",".join("0x%04X" % v for v in pal)))
    c.write("\nconst u32 selector_art_%s_tiles[SELECTOR_ART_%s_TILE_COUNT * 8] = {\n" % (sym, S))
    for t in tiles:
        c.write("    %s,\n" % ",".join("0x%08X" % r for r in t))
    c.write("};\n")
    c.write("\nconst u16 selector_art_%s_map[SELECTOR_ART_%s_TW * SELECTOR_ART_%s_TH] = {\n" % (sym, S, S))
    for r in range(th):
        c.write("    %s,\n" % ",".join("%d" % v for v in tmap[r * tw:(r + 1) * tw]))
    c.write("};\n")
c.close()
for sym, tw, th, pal, tiles, tmap in baked:
    print("%-7s %3d unique tiles  pal %s" % (sym, len(tiles), " ".join("%03X" % v for v in pal)))
