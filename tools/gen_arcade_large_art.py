#!/usr/bin/env python3
"""Extract reachable large-enemy/K kind2 art; no runtime arcade ROM image."""
from pathlib import Path
import hashlib,json
import gen_assets as G
r=Path(__file__).resolve().parents[1]
program=b''.join((r/'arcade'/n).read_bytes()for n in ('ss.01e','ss.02e','ss.03e'))
assert hashlib.sha256(program).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
def byte(a):return program[a-0x4000]
def word(a):return byte(a)*256+byte(a+1)
poses=set()
def add(code,attr):poses.add((code+((attr&32)<<3),attr&31))
def walk(root,attrs,terminal=False):
 seen=set();a=root
 while a not in seen:
  seen.add(a)
  for attr in attrs:
   for k in range(4):add(byte(a+k),attr)
  if terminal:break
  ctl=byte(a+4);a=word(a+5)if ctl&128 else a+5
  assert len(seen)<128
for a in (0xd5ce,0xd848):walk(a,range(0xfa,0xfd))
for t in (0xd987,0xd997):
 for k in range(8):walk(word(t+2*k),range(0xfa,0xfd))
walk(0xd8bc,[0xea])
for k in range(12):walk(word(0xd8a0+2*k),[0xe3,0xe4],True)
large_poses=sorted(poses)
# A cold kind2 birth retains the zeroed slot code/attribute until next update.
add(0,0)
# CECA..CEE1 normal/impact cells; verified CBC8 kind2 lifecycle.
for code in range(0x89,0x92):add(code,0xe4)
roms=G.Roms(str(r/'arcade'));frames=[];lookup={};mapping=[]
for code,bank in sorted(poses):
 pixels=G.bake_sprite_tiles(roms,code,bank)
 if pixels not in lookup:lookup[pixels]=len(frames);frames.append(pixels)
 mapping.append({'code':code,'bank':bank,'frame':lookup[pixels]})
header='''/* Generated by tools/gen_arcade_large_art.py. Local frame IDs, not VRAM. */
#ifndef ARCADE_LARGE_ART_H
#define ARCADE_LARGE_ART_H
#include "arcade_large.h"
'''
header+=f'#define ARCADE_LARGE_ART_FRAMES {len(frames)}\nextern const u32 arcade_large_art_pixels[ARCADE_LARGE_ART_FRAMES*32];\n'
header+='/* Returns 65535 for unsupported source code/attribute. */\nu16 arcade_large_art_frame(u8 code,u8 attr);\n#endif\n'
(r/'inc/arcade_large_art.h').write_text(header)
s='/* Generated by tools/gen_arcade_large_art.py. */\n#include "arcade_large_art.h"\nconst u32 arcade_large_art_pixels[ARCADE_LARGE_ART_FRAMES*32]={\n'
for p in frames:s+='    '+','.join('0x%08x'%v for v in p)+',\n'
# Attribute pages provide constant-time lookup; page0 is unsupported art.
# Frame255 is a private sentinel, expanded to the public65535 result.
assert len(frames)<255
pages=sorted(set(p['bank']|((p['code']>>8)<<5) for p in mapping))
page_ids={page:i+1 for i,page in enumerate(pages)}
table=[[255]*256 for _ in range(len(pages)+1)]
for p in mapping:
 page=p['bank']|((p['code']>>8)<<5)
 table[page_ids[page]][p['code']&255]=p['frame']
s+='};\nstatic const u8 art_page[64]={\n    '+','.join(str(page_ids.get(i,0)) for i in range(64))+'\n};\n'
s+='static const u8 art_frame[][256]={\n'
for page in table:
 s+='    {\n'
 for i in range(0,256,16):s+='        '+','.join(map(str,page[i:i+16]))+',\n'
 s+='    },\n'
s+='};\nu16 arcade_large_art_frame(u8 code,u8 attr)\n{\n    u16 frame=art_frame[art_page[attr&63]][code];\n    return frame==255?65535:frame;\n}\n'
(r/'src/arcade_large_art.c').write_text(s)
d={'program_sha256':hashlib.sha256(program).hexdigest(),'large_poses':large_poses,'mapping':mapping,'distinct_frames':len(frames),'rom_pixel_bytes':len(frames)*128,'scope':'Exact baked palette indices; local frame IDs for future renderer. No VRAM allocation or uploads yet.'}
o=r/'out/parity-audit';o.mkdir(exist_ok=True,parents=True);(o/'large-art-map.json').write_text(json.dumps(d,indent=2)+'\n');print(len(mapping),'code/bank pairs;',len(frames),'distinct frames;',len(frames)*128,'pixel bytes')
