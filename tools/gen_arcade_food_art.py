#!/usr/bin/env python3
"""Bake food characters, reusing exact resident patterns across gameplay banks."""
from pathlib import Path
import hashlib,json,re
import gen_assets as G
r=Path(__file__).resolve().parents[1];g=G.Roms(str(r/'arcade'))
rom=b''.join((r/'arcade'/n).read_bytes()for n in ['ss.01e','ss.02e','ss.03e'])
assert hashlib.sha256(rom).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
resident={};inputs={}
main_header=(r/'inc/arcade_main_art.h').read_text()
main_base=int(re.search(r'#define ARCADE_MAIN_TILE_BASE\s+(\d+)',main_header)[1])
main_count=int(re.search(r'#define ARCADE_MAIN_TILE_COUNT\s+(\d+)',main_header)[1])
inputs['inc/arcade_main_art.h']=hashlib.sha256(main_header.encode()).hexdigest()
c_art=(r/'src/arcade_c_art.c').read_text()
c_slots=[int(n)for n in re.findall(r'\d+',c_art.split('arcade_c_art_slots',1)[1].split('={',1)[1].split('}',1)[0])]
c_reserved={tile+i for tile in c_slots for i in range(4)}
inputs['src/arcade_c_art.c']=hashlib.sha256(c_art.encode()).hexdigest()
for file,symbol,base in [('src/ss_gfx.c','ss_scene_tiles',0),('src/arcade_bonus_art.c','arcade_bonus_pixels',136),('src/ss_anim.c','ss_anim_tiles',290),('src/ss_level.c','world_tiles',730)]:
    path=r/file
    if not path.exists():path=r/'res/ss_gfx.c'
    text=path.read_text();inputs[str(path.relative_to(r))]=hashlib.sha256(path.read_bytes()).hexdigest()
    data=text.split(symbol,1)[1].split('};',1)[0]
    words=[int(x,16)for x in re.findall(r'0x([0-9a-fA-F]{8})',data)]
    assert len(words)%8==0
    for i in range(0,len(words),8):
        # These captured-scene patterns are overwritten by resident main art.
        if symbol=='ss_scene_tiles' and (main_base<=base+i//8<main_base+main_count or base+i//8 in c_reserved):continue
        resident.setdefault(tuple(words[i:i+8]),base+i//8)
slots=list(range(280,288))+list(range(1372,1440));added=[];maps=[];selectors=[]
for base in [0xb403,0xb5c3]:
    poses=[]
    for food in range(-12,8):
        pattern=rom[base+food*8-0x4000:base+food*8-0x4000+8];pose=[]
        for i in range(4):
            code,attr=pattern[i],pattern[i+4]
            pixels=tuple(G.bake_char_tile(g,code+((attr&3)<<8),attr>>2))
            if pixels not in resident:
                assert len(added)<len(slots),'Food art exceeds reserved gaps'
                resident[pixels]=slots[len(added)];added.append(pixels)
            tile=resident[pixels];pose.append(tile)
            selectors.append(dict(code=code,attr=attr,tile=tile))
        poses.append(pose)
    maps.append(poses)
assert len(added)==76
# B18A entrance strip: four bottom/top character pairs, all already resident.
spawn_maps=[]
for phase in range(4):
    pair=[]
    for code in [0x1a+phase,0x0a+phase]:
        pixels=tuple(G.bake_char_tile(g,code+512,16))
        assert pixels in resident, 'Entrance strip needs an explicit new allocation'
        pair.append(resident[pixels])
    spawn_maps.append(pair)
(r/'inc/arcade_food_art.h').write_text('''/* Generated by tools/gen_arcade_food_art.py. */
#ifndef ARCADE_FOOD_ART_H
#define ARCADE_FOOD_ART_H
#include "arcade_types.h"
/* Load first8 tiles at280, remaining68 at1372; require font base>=1440.
 * Maps also borrow immutable scene/bonus/animation/world patterns. PAL0. */
#define ARCADE_FOOD_ART_TILES 76
extern const u32 arcade_food_pixels[ARCADE_FOOD_ART_TILES*8];
extern const u16 arcade_food_tiles[2][20][4];
extern const u16 arcade_food_spawn_tiles[4][2];
/* Cold load only: display off, previous DMA flushed. Rejects font overlap. */
u8 arcade_food_art_load(void);
#endif
''')
s='/* Generated by tools/gen_arcade_food_art.py. */\n#include "arcade_food_art.h"\nconst u32 arcade_food_pixels[ARCADE_FOOD_ART_TILES*8]={\n'
for pixels in added:s+='    '+','.join('0x%08x'%v for v in pixels)+',\n'
s+='};\nconst u16 arcade_food_tiles[2][20][4]={\n'
for poses in maps:s+='    {\n'+''.join('        {'+','.join(map(str,p))+'},\n'for p in poses)+'    },\n'
s+='};\nconst u16 arcade_food_spawn_tiles[4][2]={'+','.join('{'+','.join(map(str,p))+'}'for p in spawn_maps)+'};\n';(r/'src/arcade_food_art.c').write_text(s)
# Two ascending VRAM rows per DMA; keep immutable sources alive until VBlank.
columns='/* Generated by tools/gen_arcade_food_art.py. */\n#ifndef ARCADE_FOOD_COLUMNS_H\n#define ARCADE_FOOD_COLUMNS_H\nstatic const u16 food_columns[2][20][4]={\n'
for poses in maps:
 columns+='    {\n'+''.join('        {'+','.join(str(p[i]) for i in (1,0,3,2))+'},\n' for p in poses)+'    },\n'
columns+='};\n#endif\n'
(r/'inc/arcade_food_columns.h').write_text(columns)
out=r/'out/parity-audit/food-art';out.mkdir(parents=True,exist_ok=True)
(out/'manifest.json').write_text(json.dumps(dict(resident_inputs=inputs,selectors=selectors,new_tiles=76,ranges=[[280,288],[1372,1440]],scope='Baked palette indices and resident reuse; requires verified font base>=1440 and target load before publication. Live binding pending.'),indent=2)+'\n')
print('Food art:76 new tiles, two reserved ranges,40 four-tile poses')
