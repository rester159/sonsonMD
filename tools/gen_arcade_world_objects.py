#!/usr/bin/env python3
"""Extract the 348 native level objects consumed four at a time by 54E7."""
from pathlib import Path
import hashlib,json
r=Path(__file__).resolve().parents[1]
rom=b''.join((r/'arcade'/n).read_bytes() for n in ['ss.01e','ss.02e','ss.03e'])
assert hashlib.sha256(rom).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
def word(a):return int.from_bytes(rom[a-0x4000:a-0x4000+2],'big')
offsets=[(word(0x5551+i*2)-0x5587)//10 for i in range(27)]
assert offsets[0]==0 and offsets[-1]==348
objects=[]
for address in range(0x5587,0x631f,10):
    b=rom[address-0x4000:address-0x4000+10]
    objects.append(dict(address=address,x=int.from_bytes(b[4:6],'big'),
                        source_map=int.from_bytes(b[2:4],'big'),active=b[0],
                        phase=b[1],y=b[6],food=b[7],timer=b[8],kind=b[9]))
for stage in range(26):
    duration=rom[0x6485-0x4000+stage*7]
    assert offsets[stage+1]-offsets[stage]==duration*4
(r/'inc/arcade_world_objects.h').write_text('''/* Generated by tools/gen_arcade_world_objects.py. */
#ifndef ARCADE_WORLD_OBJECTS_H
#define ARCADE_WORLD_OBJECTS_H
#include "arcade_types.h"
#define ARCADE_WORLD_OBJECT_COUNT 348
/* source_map is reference metadata for translating background edits, not a
 * Genesis VRAM address. Mutable objects use native world coordinates. */
typedef struct {u16 x,source_map;u8 active,phase,y,food,timer,kind;} ArcadeWorldObject;
extern const ArcadeWorldObject arcade_world_objects[ARCADE_WORLD_OBJECT_COUNT];
extern const u16 arcade_world_object_offsets[27];
#endif
''')
s='/* Generated by tools/gen_arcade_world_objects.py. */\n#include "arcade_world_objects.h"\n'
s+='const ArcadeWorldObject arcade_world_objects[ARCADE_WORLD_OBJECT_COUNT]={\n'
for obj in objects:
    s+='    {'+','.join(str(obj[k])for k in ['x','source_map','active','phase','y','food','timer','kind'])+'},\n'
s+='};\nconst u16 arcade_world_object_offsets[27]={'+','.join(map(str,offsets))+'};\n'
(r/'src/arcade_world_objects.c').write_text(s)
out=r/'out/parity-audit/world-objects';out.mkdir(parents=True,exist_ok=True)
d=dict(program_sha256=hashlib.sha256(rom).hexdigest(),objects=objects,offsets=offsets,
       scope='Immutable source placements for all object kinds; live pool, streaming and rendering binding pending.')
(out/'manifest.json').write_text(json.dumps(d,indent=2)+'\n')
print('Extracted',len(objects),'objects across26 segments')
