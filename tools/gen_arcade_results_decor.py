#!/usr/bin/env python3
"""Extract992C decoration poses, positions and exact graphics."""
from pathlib import Path
import hashlib,json
import gen_assets as G
r=Path(__file__).resolve().parents[1];g=G.Roms(str(r/'arcade'))
rom=b''.join((r/'arcade'/n).read_bytes()for n in ('ss.01e','ss.02e','ss.03e'))
sha=hashlib.sha256(rom).hexdigest()
assert sha=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
positions=[];poses=[];pixels=[]
for i in range(3):
 p=0x5962+i*5;root=int.from_bytes(rom[p:p+2],'big')
 positions.append((int.from_bytes(rom[p+2:p+4],'big'),rom[p+4]))
 frames=[]
 for f in range(2):
  a=root-0x4000+f*3;code,attr,timer=rom[a:a+3]
  if f:assert timer&128 and int.from_bytes(rom[a+3:a+5],'big')==root
  else:assert timer<128
  tile=len(pixels)//8
  pixels.extend(G.bake_sprite_tiles(g,code+((attr&32)<<3),attr&31))
  frames.append((tile,code,attr,timer&127))
 poses.append(frames)
assert len(pixels)==24*8
assert positions==[(144,32),(80,32),(112,32)]
assert [[p[3]for p in row]for row in poses]==[[10,16]]*3
s='/* Generated by tools/gen_arcade_results_decor.py. */\n#include "arcade_results_decor.h"\n'
s+='const ArcadeResultsPosition arcade_results_positions[3]={'+','.join('{%d,%d}'%p for p in positions)+'};\n'
s+='const ArcadeResultsPose arcade_results_poses[3][2]={\n'+''.join('{'+','.join('{%d,%d,%d,%d}'%f for f in row)+'},\n'for row in poses)+'};\n'
s+='const u32 arcade_results_decor_pixels[24*8]={\n'+''.join(','.join('0x%08x'%v for v in pixels[i:i+8])+',\n'for i in range(0,len(pixels),8))+'};\n'
(r/'src/arcade_results_decor_data.c').write_text(s)
o=r/'out/parity-audit/results-decor';o.mkdir(parents=True,exist_ok=True)
report={'source_sha256':sha,'positions':positions,'poses':poses,'tiles':24,
 'scope':'Three992C decoration actors. Player and marker actors preserve their existing animation state; they are not initialized to new fixed poses by9898/98DF.'}
(o/'manifest.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report,indent=2))
