"""gen_shop.py -- the shop scene's background for the Genesis renderer.

Input: out/ss2/shop_s1.pkl, the research model paused on the stage-1 shop
screen (research/npc/cap.py SAVE=240 SAVEPKL=..., the s1shop48 setup).
The shop picture (bank 2 $7A5E blocks, bank 0 $FBB1 layout, the goods
panel and END) is the same for every shop; the camera is at 0, so the
playfield shows BAT rows 7-29 and world tiles equal BAT cells. Price cells
(BAT $588/$593/$648/$653, 5 digits) and the staff digit ($5C5) are drawn
at run time and blanked here; the text window interior is cleared by the
window code. Goods icons, shopkeeper and cursor are sprites (renderer).

Output: src/ss2_shop_data.c, inc/ss2_shop_data.h: two CRAM lines (0-1,
replacing the stage BG while the shop is up), the deduplicated tiles, the
23x32 map (Genesis words, tile index relative to the load base) and the
price digit words (PCE tile $1B0+d, palette 15).
"""
import os, pickle, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.setrecursionlimit(10000)
import render
from gen_ss2 import TileBank, fit_lines, gen_colour, c_array, ROOT

ROWS = range(7, 30)
BLANK = 0x01A0                              # $A649's fill word


def main():
    m = pickle.load(open(os.path.join(ROOT, 'out', 'ss2', 'shop_s1.pkl'), 'rb'))
    bw, _ = render.bg_size(m.vreg)
    bat = lambda r, c: m.vram[r * bw + c]
    blanks = set()
    for a in (0x588, 0x593, 0x648, 0x653):
        for i in range(5):
            blanks.add((a >> 6, (a & 63) + i))
    blanks.add((0x5C5 >> 6, 0x5C5 & 63))
    window = {(r, c) for r in range(0x0B, 0x11) for c in range(0x13, 0x1D)}   # $69EE clears it
    cells = [[BLANK if (r, c) in blanks else 0x1202 if (r, c) in window else bat(r, c)
              for c in range(32)] for r in ROWS]
    digits = [0xF1B0 + d for d in range(10)]
    colour = lambda p, c: m.cram[p * 16 + c] if c else m.cram[0]
    weights = {}
    for w in [w for row in cells for w in row] + digits:
        p = w >> 12
        for r in render.tile_pixels(m.vram, w & 0xFFF):
            for c in r:
                d = weights.setdefault(p, {})
                col = colour(p, c)
                d[col] = d.get(col, 0) + 1
    assign, maps, lines = fit_lines(weights, 2)
    bank = TileBank()
    bank.add([[0] * 8] * 8)

    def word(w):
        p = w >> 12
        li = assign[p]
        px = [[lines[li].index[maps[li][colour(p, c)]] for c in r] for r in render.tile_pixels(m.vram, w & 0xFFF)]
        idx, flags = bank.add(px)
        return (li << 13) | flags | idx

    mp = [word(w) for row in cells for w in row]
    dg = [word(w) for w in digits]
    pal = lines[0].words() + lines[1].words()
    src = ['/* Generated by tools/ss2/gen_shop.py. Do not edit. */', '#include "ss2_shop_data.h"', '',
           c_array('ss2_shop_palette', 'u16', pal),
           c_array('ss2_shop_tiles', 'u32', bank.words(), 8, '0x%08X'),
           c_array('ss2_shop_map', 'u16', mp, 32),
           c_array('ss2_shop_digit', 'u16', dg)]
    open(os.path.join(ROOT, 'src', 'ss2_shop_data.c'), 'w').write('\n'.join(src))
    open(os.path.join(ROOT, 'inc', 'ss2_shop_data.h'), 'w').write('''/* Generated by tools/ss2/gen_shop.py. Do not edit. */
#ifndef SS2_SHOP_DATA_H
#define SS2_SHOP_DATA_H
#include <genesis.h>

#define SS2_SHOP_NTILES   %d
#define SS2_SHOP_ROW0     7         /* BAT row of ss2_shop_map row 0 */
#define SS2_SHOP_ROWS     %d

extern const u16 ss2_shop_palette[32];                 /* CRAM lines 0-1 */
extern const u32 ss2_shop_tiles[SS2_SHOP_NTILES * 8];
extern const u16 ss2_shop_map[SS2_SHOP_ROWS * 32];     /* line << 13 | flips | tile */
extern const u16 ss2_shop_digit[10];                   /* price digits 0-9 */

#endif
''' % (len(bank.tiles), len(ROWS)))
    print('shop: %d tiles, lines %s' % (len(bank.tiles), [len(l.colours) - 1 for l in lines]))


if __name__ == '__main__':
    main()
