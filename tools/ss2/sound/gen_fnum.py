#!/usr/bin/env python3
"""gen_fnum.py -- write src/ss2_sound_fnum.c: the YM block|fnum word for
every 12-bit PCE period, for the NTSC and PAL YM clocks. Same integer maths
as ss2_sound.c's render_fm (q = K / per, halved into blocks 0-7, capped)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
K = {'ntsc': 4404020, 'pal': 4444559}     # the K constants in ss2_sound.c

def word(k, per):
    if per == 0:
        return 0                            # never used (a channel needs per)
    q = k // per
    blk = 0
    while q > 2047 and blk < 7:
        q >>= 1
        blk += 1
    if q > 2047:
        q = 2047
    return (blk << 11) | q

out = ['/* Generated by tools/ss2/sound/gen_fnum.py. Do not edit. */', '#include <genesis.h>', '']
for name, k in K.items():
    vals = [word(k, p) for p in range(4096)]
    out.append('const u16 ss2_fnum_%s[4096] = {' % name)
    for i in range(0, 4096, 16):
        out.append('    ' + ','.join('0x%04X' % v for v in vals[i:i + 16]) + ',')
    out.append('};')
    out.append('')
open(os.path.join(ROOT, 'src', 'ss2_sound_fnum.c'), 'w').write('\n'.join(out))
