"""gen_scene.py -- full-screen pictures shown over the playfield (scenes other
than the title, which has gen_title.py): their BAT words -> Genesis tiles.

Each scene comes from a research-model pickle taken while it is up. The
picture's BAT words in BAT rows 7-29 (the playfield under the HUD) become
a sorted key table with tiles and a 2-line BG palette (CRAM lines 0-1;
lines 2-3 stay the HUD/sprite lines). Font, box and window words (palettes
1/5/15 at tiles $180-$23F, the blank $01A0) are left to the play-scene
glyph path.

Scenes (ss2_scene ids, inc/ss2_logic.h):
  2 CONTINUE  out/ss2/cont_s.pkl    the revive picture (bank 2 $7ADE, $FBB1 $FC32)
  3 ENDING    out/ss2/ending_s.pkl  (when present)

Output: src/ss2_scene_data.c, inc/ss2_scene_data.h (ss2_scene_bg[]).
"""
import os, pickle, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.setrecursionlimit(10000)
import render
from gen_ss2 import c_array, ROOT, fit_lines

SCENES = [('continue', 'cont_s.pkl', range(7, 30)), ('ending', 'ending_s.pkl', range(0, 30))]


def glyph(w):
    p, t = w >> 12, w & 0xFFF
    return w == 0x01A0 or (p in (1, 5, 15) and 0x180 <= t < 0x240)


def convert(m, rows):
    bw, _ = render.bg_size(m.vreg)
    words = sorted({m.vram[r * bw + c] for r in rows for c in range(64)} - {w for w in range(0x10000) if glyph(w)})
    colour = lambda p, c: m.cram[p * 16 + c] if c else m.cram[0]
    weights = {}
    for w in words:
        p = w >> 12
        for r in render.tile_pixels(m.vram, w & 0xFFF):
            for c in r:
                d = weights.setdefault(p, {})
                d[colour(p, c)] = d.get(colour(p, c), 0) + 1
    assign, maps, lines = fit_lines(weights, 2)
    tiles, tline = [], []
    for w in words:
        p = w >> 12
        li = assign[p]
        for r in render.tile_pixels(m.vram, w & 0xFFF):
            v = 0
            for c in r:
                v = (v << 4) | lines[li].index[maps[li][colour(p, c)]]
            tiles.append(v)
        tline.append(li)
    return words, tiles, tline, lines[0].words() + lines[1].words()


def main():
    src = ['/* Generated by tools/ss2/gen_scene.py. Do not edit. */', '#include "ss2_scene_data.h"', '']
    desc = []
    for name, pkl, rows in SCENES:
        path = os.path.join(ROOT, 'out', 'ss2', pkl)
        if not os.path.exists(path):
            desc.append('    { 0, 0, 0, 0, 0 },          /* %s: not captured yet */' % name)
            continue
        words, tiles, tline, pal = convert(pickle.load(open(path, 'rb')), rows)
        n = 'ss2_scene_%s' % name
        src += [c_array(n + '_palette', 'u16', pal), c_array(n + '_keys', 'u16', words),
                c_array(n + '_tiles', 'u32', tiles, 8, '0x%08X'), c_array(n + '_line', 'u8', tline, 16, '0x%02X')]
        desc.append('    { %s_palette, %s_keys, %s_tiles, %s_line, %d },' % (n, n, n, n, len(words)))
        print('%s: %d BAT words' % (name, len(words)))
    src.append('const Ss2SceneBg ss2_scene_bg[%d] = {\n%s\n};\n' % (len(SCENES), '\n'.join(desc)))
    open(os.path.join(ROOT, 'src', 'ss2_scene_data.c'), 'w').write('\n'.join(src))
    open(os.path.join(ROOT, 'inc', 'ss2_scene_data.h'), 'w').write('''/* Generated by tools/ss2/gen_scene.py. Do not edit. */
#ifndef SS2_SCENE_DATA_H
#define SS2_SCENE_DATA_H
#include <genesis.h>

/* a picture scene: tiles keyed by BAT word, CRAM lines 0-1 */
typedef struct
{
    const u16 *palette;         /* 32 words */
    const u16 *keys;            /* sorted BAT words */
    const u32 *tiles;
    const u8 *line;             /* CRAM line 0/1 per key */
    u16 nkeys;
} Ss2SceneBg;

#define SS2_SCENE_BG_FIRST 2    /* ss2_scene_bg[id - 2] */
extern const Ss2SceneBg ss2_scene_bg[%d];

#endif
''' % len(SCENES))


if __name__ == '__main__':
    main()
