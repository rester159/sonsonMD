"""gen_title.py -- the title scene's tiles and palettes for the Genesis renderer.

Input: out/ss2/title_s.pkl, the research model 330 frames after power-on
(title picture up, logo animating). The title (bank 0 $E330) draws its
picture with $FBB1 (map $E6D7) over blocks loaded by bank 2 $7B02, its text
with $BAD9 and the high score as BAT words; the native code issues those as
BAT writes, so the renderer needs a tile for every BAT word they use.

Output: src/ss2_title_data.c, inc/ss2_title_data.h:
  ss2_title_palette[64]   CRAM: lines 0-1 the picture, 2-3 the sprites
  ss2_title_keys[]        sorted BAT words, ss2_title_tiles / _line per key
  ss2_title_cmap[16*8]    sprite palette -> (line-2) << 7 | index
"""
import os, pickle, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.setrecursionlimit(10000)
import render
import palfit
from gen_ss2 import LinePalette, c_array, ROOT, fit_lines


def cdist(a, b):
    return sum((((a >> sh) & 7) - ((b >> sh) & 7)) ** 2 for sh in (0, 3, 6))


def main():
    m = pickle.load(open(os.path.join(ROOT, 'out', 'ss2', 'title_s.pkl'), 'rb'))
    bw, _ = render.bg_size(m.vreg)
    words = {m.vram[r * bw + c] for r in range(30) for c in range(64)}
    words |= {0xF1B0 + d for d in range(10)} | {0xF1A0}          # high score digits
    words |= {0xF180 + c for c in range(0x20, 0x60)}             # the font: Genesis OPTIONS menu
    words = sorted(words)
    colour = lambda p, c: m.cram[p * 16 + c] if c else m.cram[0]
    weights = {}
    for w in words:
        p = w >> 12
        for r in render.tile_pixels(m.vram, w & 0xFFF):
            for c in r:
                d = weights.setdefault(p, {})
                d[colour(p, c)] = d.get(colour(p, c), 0) + 1
    assign, maps, lines = fit_lines(weights, 2)
    tiles, tline = [], []
    for w in words:
        p = w >> 12
        li = assign[p]
        for r in render.tile_pixels(m.vram, w & 0xFFF):
            v = 0
            for c in r:
                v = (v << 4) | lines[li].index[maps[li][colour(p, c)]]
            tiles.append(v)
        tline.append(li)
    # sprites: the palettes of the title objects (records $E621/$E637/$E64D
    # and the later $255B values $84/$89: palettes 0, 3, 4, 9, 11)
    sw = {}
    for p in (0, 3, 4, 9, 11):
        for c in range(1, 8):
            col = m.cram[256 + p * 16 + c]
            d = sw.setdefault(p, {})
            d[col] = d.get(col, 0) + 1
    sassign, smaps, slines = fit_lines(sw, 2)

    def near(li, col):
        return min(range(1, len(slines[li].colours)), key=lambda i: cdist(slines[li].colours[i], col))
    cmap = []
    for p in range(16):
        cols = [m.cram[256 + p * 16 + c] for c in range(8)]
        if p in sassign:
            li = sassign[p]
            idx = [slines[li].index[smaps[li][cols[c]]] if cols[c] in smaps[li] else near(li, cols[c])
                   for c in range(1, 8)]
        else:
            li = min([l for l in range(2) if len(slines[l].colours) > 1],
                     key=lambda l: sum(cdist(slines[l].colours[near(l, c)], c) for c in cols[1:]))
            idx = [near(li, c) for c in cols[1:]]
        cmap += [0] + [(li << 7) | i for i in idx]
    # the intro's sprite palettes 8-15 (bank 2 $65DC: $FF8E from $4A6C,
    # silhouettes) on stage 1's sprite lines 2-3 (src/ss2_data.c)
    import re
    from gen_ss2 import ROM, gen_colour
    data = open(os.path.join(ROOT, 'src', 'ss2_data.c')).read()
    def gdist(g, c):
        w = gen_colour(c)
        return sum((((g >> sh) & 7) - ((w >> sh) & 7)) ** 2 for sh in (1, 5, 9))
    icmap = []
    for s, p in [(s, p) for s in range(7) for p in range(8)]:      # per stage (the ending tally is on stage 7)
        sp = [int(v, 16) for v in re.findall(r'0x[0-9A-F]+', re.search(r'ss2_s%d_palette\[64\] = \{(.*?)\};' % s, data, re.S).group(1))]
        gl = [sp[32:48], sp[48:64]]
        cols = [ROM[0x2A6C + p * 16 + c * 2] | (ROM[0x2A6C + p * 16 + c * 2 + 1] << 8) for c in range(8)]   # 8 colours per palette ($FF8E)
        best = None
        for li in range(2):
            idx = [min(range(1, 16), key=lambda i: gdist(gl[li][i], cols[c])) for c in range(1, 8)]
            err = sum(gdist(gl[li][idx[c - 1]], cols[c]) for c in range(1, 8))
            if best is None or err < best[0]:
                best = (err, li, idx)
        icmap += [0] + [(best[1] << 7) | i for i in best[2]]
    pal = lines[0].words() + lines[1].words() + slines[0].words() + slines[1].words()
    src = ['/* Generated by tools/ss2/gen_title.py. Do not edit. */', '#include "ss2_title_data.h"', '',
           c_array('ss2_title_palette', 'u16', pal),
           c_array('ss2_title_keys', 'u16', words),
           c_array('ss2_title_tiles', 'u32', tiles, 8, '0x%08X'),
           c_array('ss2_title_line', 'u8', tline, 16, '0x%02X'),
           c_array('ss2_title_cmap', 'u8', cmap, 16, '0x%02X'),
           c_array('ss2_intro_cmap', 'u8', icmap, 16, '0x%02X')]
    open(os.path.join(ROOT, 'src', 'ss2_title_data.c'), 'w').write('\n'.join(src))
    open(os.path.join(ROOT, 'inc', 'ss2_title_data.h'), 'w').write('''/* Generated by tools/ss2/gen_title.py. Do not edit. */
#ifndef SS2_TITLE_DATA_H
#define SS2_TITLE_DATA_H
#include <genesis.h>

#define SS2_TITLE_NKEYS %d

extern const u16 ss2_title_palette[64];   /* lines 0-1 picture, 2-3 sprites */
extern const u16 ss2_title_keys[SS2_TITLE_NKEYS];   /* sorted BAT words */
extern const u32 ss2_title_tiles[SS2_TITLE_NKEYS * 8];
extern const u8  ss2_title_line[SS2_TITLE_NKEYS];   /* CRAM line 0/1 */
extern const u8  ss2_title_cmap[16 * 8];            /* sprite palette, colour -> (line-2) << 7 | index */
extern const u8  ss2_intro_cmap[7 * 8 * 8];         /* sprite palettes 8-15 from $4A6C (intro, ending tally) per stage's lines */

#endif
''' % len(words))
    print('title: %d BAT words, bg lines %s, sprite palettes %s lines %s'
          % (len(words), [len(l.colours) - 1 for l in lines], sorted(sassign), [len(l.colours) - 1 for l in slines]))


if __name__ == '__main__':
    main()
