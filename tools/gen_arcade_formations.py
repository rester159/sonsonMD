#!/usr/bin/env python3
"""Extract G/H formation selectors; all addresses are main MC6809 ss.01e/02e/03e."""
from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parents[1]
rom=b''.join((root/'arcade'/n).read_bytes() for n in ['ss.01e','ss.02e','ss.03e'])
assert hashlib.sha256(rom).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
def read(a,n):
 assert 0x4000<=a and a+n<=0x10000
 return rom[a-0x4000:a-0x4000+n]
s='/* Generated by tools/gen_arcade_formations.py; source revision checked. */\n#include "arcade_types.h"\nconst u8 arcade_formations[2][4][48]={\n'
pointers=[]
for table in [0xF72B,0xF8B2]:
 ptr=[int.from_bytes(read(table+g*2,2),'big') for g in range(4)]
 pointers.append(ptr);s+='    {\n'
 for p in ptr:s+='        {'+','.join('0x%02X'%b for b in read(p,48))+'},\n'
 s+='    },\n'
s+='};\n'
(root/'src/arcade_formations.c').write_text(s)
(root/'out/parity-audit/formation-extraction.json').write_text(json.dumps({'program_sha256':hashlib.sha256(rom).hexdigest(),'pointer_tables':['F72B','F8B2'],'pointers':pointers,'G_selector_stride':2,'H_selector_stride':12},indent=2)+'\n')
print('Extracted exact G/H formations, 384 bytes')
