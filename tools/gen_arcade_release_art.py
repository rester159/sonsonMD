#!/usr/bin/env python3
"""Bake the eight A893 poses; share exact pixels with immutable world art."""
from pathlib import Path
import hashlib,re,json
import gen_assets as G
r=Path(__file__).resolve().parents[1];g=G.Roms(str(r/'arcade'))
rom=b''.join((r/'arcade'/f).read_bytes()for f in ('ss.01e','ss.02e','ss.03e'))
assert hashlib.sha256(rom).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
base=int(re.search(r'#define SS_LEVEL_TILE_BASE\s+(\d+)',(r/'inc/ss_level.h').read_text())[1])
source=(r/'src/ss_level.c').read_text().split('world_tiles',1)[1].split('};',1)[0]
words=[int(v,16) for v in re.findall(r'0x([0-9a-fA-F]{8})',source)]
resident={tuple(words[i:i+8]):base+i//8 for i in range(0,len(words),8)}
tiles=[];maps=[]
for frame in range(8):
    pattern=rom[0x68e2+frame*8:0x68ea+frame*8];pose=[]
    for k in range(4):
        a=pattern[k+4]
        pixels=tuple(G.bake_char_tile(g,pattern[k]+((a&3)<<8),a>>2))
        if pixels not in resident:
            if pixels not in tiles:tiles.append(pixels)
            tile=2032+tiles.index(pixels)
        else:tile=resident[pixels]
        pose.append(tile)
    maps.append(pose)
assert len(tiles)<=16,'Release art exceeds free FE00..FFFF arena'
(r/'inc/arcade_release_art.h').write_text('''#ifndef ARCADE_RELEASE_ART_H
#define ARCADE_RELEASE_ART_H
#include "arcade_types.h"
#define ARCADE_RELEASE_TILE_BASE 2032
#define ARCADE_RELEASE_TILE_COUNT %d
extern const u32 arcade_release_pixels[ARCADE_RELEASE_TILE_COUNT*8];
extern const u16 arcade_release_tiles[8][4];
void arcade_release_background_reset(void);
void arcade_release_background_begin(void);
void arcade_release_background_step(u16 camera,u8 clock,u8 plane_phase);
void arcade_release_background_render(void);
#endif
'''%len(tiles))
(r/'src/arcade_release_art.c').write_text('/* Generated by tools/gen_arcade_release_art.py. */\n#include "arcade_release_art.h"\nconst u32 arcade_release_pixels[ARCADE_RELEASE_TILE_COUNT*8]={\n'+''.join(','.join('0x%08x'%v for v in t)+',\n'for t in tiles)+'};\nconst u16 arcade_release_tiles[8][4]={\n'+''.join('{'+','.join(map(str,p))+'},\n'for p in maps)+'};\n')
o=r/'out/parity-audit/release-art';o.mkdir(parents=True,exist_ok=True)
report=dict(new_tiles=len(tiles),poses=8,vram_start=2032*32,vram_end=(2032+len(tiles))*32,world_sha256=hashlib.sha256((r/'src/ss_level.c').read_bytes()).hexdigest())
(o/'manifest.json').write_text(json.dumps(report,indent=2)+'\n');print(report)
