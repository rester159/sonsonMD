#!/usr/bin/env python3
"""Original title HUD glyphs in source banks44/56/08/0C/10."""
from pathlib import Path
import gen_assets as G
r=Path(__file__).resolve().parents[1];gfx=G.Roms(str(r/'arcade'));tiles=[];lookup=[]
for attr in (44,56,8,12,16):
 row=[]
 for code in range(43):
  tile=tuple(G.bake_char_tile(gfx,code,attr>>2))
  if tile not in tiles:tiles.append(tile)
  row.append(tiles.index(tile))
 lookup.append(row)
assert 1003+len(tiles)<=1376
(r/'inc/arcade_prelude_hud_art.h').write_text('''/* Generated by tools/gen_prelude_hud.py. */
#ifndef ARCADE_PRELUDE_HUD_ART_H
#define ARCADE_PRELUDE_HUD_ART_H
#include "arcade_types.h"
#define ARCADE_PRELUDE_HUD_BASE 1003
#define ARCADE_PRELUDE_HUD_TILES '''+str(len(tiles))+'''
extern const u32 arcade_prelude_hud_pixels[ARCADE_PRELUDE_HUD_TILES*8];
extern const u16 arcade_prelude_hud_glyphs[5][43];
#endif
''')
s='#include "arcade_prelude_hud_art.h"\nconst u32 arcade_prelude_hud_pixels[ARCADE_PRELUDE_HUD_TILES*8]={\n'
for t in tiles:s+=' '+','.join('0x%08x'%x for x in t)+',\n'
s+='};\nconst u16 arcade_prelude_hud_glyphs[5][43]={\n'
for row in lookup:s+=' {'+','.join(map(str,row))+'},\n'
s+='};\n';(r/'src/arcade_prelude_hud_art.c').write_text(s)
print(len(tiles),'HUD tiles')
