#!/usr/bin/env python3
"""Extract the shared converted-enemy collectible/score poses from B291."""
from pathlib import Path
import hashlib,json
import gen_assets as G
r=Path(__file__).resolve().parents[1]
rom=b''.join((r/'arcade'/n).read_bytes() for n in ['ss.01e','ss.02e','ss.03e'])
assert hashlib.sha256(rom).hexdigest()=='09243a5a27a14d1e31db7456e1795016cd4da6466dc7735a1852eb102d8400d1'
def byte(a):assert 0x4000<=a<0x10000;return rom[a-0x4000]
def word(a):return byte(a)*256+byte(a+1)
roots=[word(0xb291+i*2) for i in range(11)]
addresses=sorted(set(roots+[a+3 for a in roots]));ids={a:i for i,a in enumerate(addresses)}
frames=[];pixels=[];seen={};poses=[];roms=G.Roms(str(r/'arcade'))
def tile(code,attr):
 key=(code+((attr&32)<<3),attr&31)
 baked=G.bake_sprite_tiles(roms,*key)
 if baked not in seen:seen[baked]=len(pixels);pixels.append(baked)
 local=seen[baked];poses.append({'code':key[0],'bank':key[1],'frame':local})
 return 136+local*4
for a in addresses:
 code,attr,ctl=byte(a),byte(a+1),byte(a+2)
 nxt=word(a+3) if ctl&128 else a+3
 assert nxt in ids
 normal=tile(code,attr)
 # Phase0 displays a fruit; phase2 advances to the score pose and may use C3.
 alt=tile(code,0xc3) if a not in roots else 65535
 frames.append({'address':a,'next':ids[nxt],'code':code,'attr':attr,'timer':ctl&127,'tile':normal,'owner2_tile':alt})
assert 136+4*len(pixels)<=290,'Bonus art exceeds unoccupied pre-animation arena'
header='''/* Generated by tools/gen_arcade_bonus_art.py. */
#ifndef ARCADE_BONUS_ART_H
#define ARCADE_BONUS_ART_H
#include "arcade_types.h"
#define ARCADE_BONUS_TILE_BASE 136
'''+f'#define ARCADE_BONUS_TILE_COUNT {len(pixels)*4}\n'+'''typedef struct {u16 next,tile,owner2_tile;u8 code,attr,timer;} ArcadeBonusFrame;
extern const u32 arcade_bonus_pixels[ARCADE_BONUS_TILE_COUNT*8];
extern const ArcadeBonusFrame arcade_bonus_frames[22];
extern const u16 arcade_bonus_roots[11];
/* B327: kind10 score code by section-clear grade; palettes C4/C3. */
extern const u8 arcade_variant_score_codes[7];
#endif
'''
(r/'inc/arcade_bonus_art.h').write_text(header)
s='/* Generated by tools/gen_arcade_bonus_art.py. */\n#include "arcade_bonus_art.h"\nconst u32 arcade_bonus_pixels[ARCADE_BONUS_TILE_COUNT*8]={\n'
for p in pixels:s+='    '+','.join('0x%08x'%v for v in p)+',\n'
s+='};\nconst ArcadeBonusFrame arcade_bonus_frames[22]={\n'
for f in frames:s+='    {%d,%d,%d,%d,%d,%d},\n'%tuple(f[k]for k in ['next','tile','owner2_tile','code','attr','timer'])
s+='};\nconst u16 arcade_bonus_roots[11]={'+','.join(str(ids[a])for a in roots)+'};\n'
variant_codes=[byte(0xb327+i*6) for i in range(7)]
for i,code in enumerate(variant_codes):
 assert [byte(0xb327+i*6+j) for j in range(6)]==[code,0xc4,255,code,0xc3,255]
 assert any(f['code']==code and f['owner2_tile']!=65535 for f in frames)
s+='const u8 arcade_variant_score_codes[7]={'+','.join(map(str,variant_codes))+'};\n'
(r/'src/arcade_bonus_art.c').write_text(s)
d={'source_sha256':hashlib.sha256(rom).hexdigest(),'frames':frames,'roots':[ids[a]for a in roots],'poses':poses,'distinct_cells':len(pixels),'tile_begin':136,'tile_end':136+len(pixels)*4,'scope':'Reachable normal conversion fruit and collected score poses for both owners; not yet loaded by game_init.'}
(r/'out/parity-audit/bonus-art-map.json').write_text(json.dumps(d,indent=2)+'\n');print(json.dumps({k:d[k]for k in ['distinct_cells','tile_begin','tile_end']},indent=2))
